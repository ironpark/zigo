const std = @import("std");
const emit = @import("emit.zig");
const lower = @import("lower.zig");
const semantic = @import("semantic");
const validate = @import("validate.zig");

pub const Options = struct {
    package: []const u8,
    prefix: []const u8,
    go_module: []const u8,
    include_dir: []const u8 = "${SRCDIR}/../../../zig-out/include",
    library_dir: []const u8 = "${SRCDIR}/../../../zig-out/lib",
};

pub fn generate(allocator: std.mem.Allocator, io: std.Io, semantic_bytes: []const u8, output: std.Io.Dir, options: Options) !void {
    var parsed = try semantic.Semantic.parse(allocator, semantic_bytes);
    defer parsed.deinit();
    try validate.semanticDocument(parsed.value);
    const program = try lower.semanticDocument(allocator, parsed.value, options.package, options.prefix);
    const emitter_options: emit.Options = .{
        .go_module = options.go_module,
        .include_dir = options.include_dir,
        .library_dir = options.library_dir,
    };
    for (emit.all) |emitter| {
        const relative_path = try emitter.pathAlloc(allocator, program);
        defer allocator.free(relative_path);
        if (std.fs.path.dirname(relative_path)) |directory| try output.createDirPath(io, directory);
        var rendered: std.Io.Writer.Allocating = .init(allocator);
        defer rendered.deinit();
        try emitter.render(allocator, &rendered.writer, program, emitter_options);
        try output.writeFile(io, .{ .sub_path = relative_path, .data = rendered.written() });
    }
}

test "scalar IR generates matching shim header raw and public packages" {
    const fixture =
        \\{
        \\  "functions": [
        \\    {
        \\      "name": "add",
        \\      "params": [
        \\        {"name":"p0","type":{"bits":32,"kind":"int","signed":true}},
        \\        {"name":"p1","type":{"bits":32,"kind":"int","signed":true}}
        \\      ],
        \\      "return": {"bits":32,"kind":"int","signed":true},
        \\      "symbol": "ignored"
        \\    }
        \\  ],
        \\  "package": "scalar",
        \\  "prefix": "zg",
        \\  "zig_version": "0.16.0"
        \\}
    ;
    var temporary = std.testing.tmpDir(.{ .iterate = true });
    defer temporary.cleanup();
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    try generate(arena.allocator(), std.testing.io, fixture, temporary.dir, .{
        .package = "scalar",
        .prefix = "zg",
        .go_module = "example.com/zigo/scalar",
    });

    const expected = [_]struct { path: []const u8, content: []const u8 }{
        .{ .path = "shim.zig", .content =
        \\// Code generated by zigo. DO NOT EDIT.
        \\const target = @import("zigo_target");
        \\
        \\export fn zg_add(p0: i32, p1: i32) i32 {
        \\    return target.add(p0, p1);
        \\}
        \\
        },
        .{ .path = "zigo_scalar.h", .content =
        \\// Code generated by zigo. DO NOT EDIT.
        \\#ifndef ZIGO_scalar_H
        \\#define ZIGO_scalar_H
        \\
        \\#include <stddef.h>
        \\#include <stdint.h>
        \\
        \\int32_t zg_add(int32_t p0, int32_t p1);
        \\
        \\#endif // ZIGO_scalar_H
        \\
        },
        .{ .path = "internal/raw/raw.go", .content =
        \\// Code generated by zigo. DO NOT EDIT.
        \\package raw
        \\
        \\/*
        \\#cgo CFLAGS: -I${SRCDIR}/../../../zig-out/include
        \\#cgo LDFLAGS: -L${SRCDIR}/../../../zig-out/lib -lscalar_zigo
        \\#include "zigo_scalar.h"
        \\*/
        \\import "C"
        \\
        \\func Add(p0 int32, p1 int32) int32 {
        ++ "\n\treturn int32(C.zg_add(C.int32_t(p0), C.int32_t(p1)))\n" ++
            \\}
            \\
        },
        .{ .path = "scalar/generated.go", .content =
        \\// Code generated by zigo. DO NOT EDIT.
        \\package scalar
        \\
        \\import "example.com/zigo/scalar/internal/raw"
        \\
        \\func Add(p0 int32, p1 int32) int32 {
        ++ "\n\treturn raw.Add(p0, p1)\n" ++
            \\}
            \\
        },
    };
    for (expected) |file| {
        const contents = try temporary.dir.readFileAlloc(std.testing.io, file.path, std.testing.allocator, .limited(16 * 1024));
        defer std.testing.allocator.free(contents);
        try std.testing.expectEqualStrings(file.content, contents);
    }
}

test "bool is lowered to uint8 at the ABI boundary" {
    const fixture =
        \\{"functions":[{"name":"negate","params":[{"name":"p0","type":{"kind":"bool"}}],"return":{"kind":"bool"},"symbol":"ignored"}],"package":"scalar","prefix":"zg","zig_version":"0.16.0"}
    ;
    var temporary = std.testing.tmpDir(.{ .iterate = true });
    defer temporary.cleanup();
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    try generate(arena.allocator(), std.testing.io, fixture, temporary.dir, .{ .package = "scalar", .prefix = "zg", .go_module = "example.com/zigo/scalar" });
    const header = try temporary.dir.readFileAlloc(std.testing.io, "zigo_scalar.h", std.testing.allocator, .limited(16 * 1024));
    defer std.testing.allocator.free(header);
    try std.testing.expect(std.mem.containsAtLeast(u8, header, 1, "uint8_t zg_negate(uint8_t p0)"));
}
