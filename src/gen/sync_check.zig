const std = @import("std");
const go_walk = @import("go_walk.zig");

pub const DifferenceKind = enum { missing, content, obsolete };
pub const Difference = struct { kind: DifferenceKind, path: []const u8 };

const generated_marker = "// Code generated by zigo. DO NOT EDIT.";
const volatile_cgo_link_file = "zigo_link_inputs_gen.go";

pub const Result = struct {
    differences: std.ArrayList(Difference) = .empty,

    pub fn deinit(self: *Result, allocator: std.mem.Allocator) void {
        for (self.differences.items) |difference| allocator.free(difference.path);
        self.differences.deinit(allocator);
    }

    pub fn matches(self: Result) bool {
        return self.differences.items.len == 0;
    }

    pub fn render(self: Result, writer: *std.Io.Writer) !void {
        for (self.differences.items) |difference| {
            try writer.print("generated file {s}: {s}\n", .{ @tagName(difference.kind), difference.path });
        }
    }
};

/// Compare only generated Go files. Other source files in go_dir belong to the
/// consumer and are deliberately outside the check's scope.
pub fn compare(allocator: std.mem.Allocator, io: std.Io, generated: std.Io.Dir, go_dir: std.Io.Dir) !Result {
    var result: Result = .{};
    errdefer result.deinit(allocator);
    var walker = try go_walk.walk(generated, allocator);
    defer walker.deinit();
    while (try walker.next(io)) |entry| {
        if (entry.kind != .file or !std.mem.endsWith(u8, entry.path, ".go")) continue;
        const actual = go_dir.readFileAlloc(io, entry.path, allocator, .limited(64 * 1024 * 1024)) catch |err| switch (err) {
            error.FileNotFound => {
                try append(allocator, &result, .missing, entry.path);
                continue;
            },
            else => return err,
        };
        defer allocator.free(actual);
        const expected = try generated.readFileAlloc(io, entry.path, allocator, .limited(64 * 1024 * 1024));
        defer allocator.free(expected);
        if (!std.mem.eql(u8, expected, actual)) try append(allocator, &result, .content, entry.path);
    }

    var source_walker = try go_walk.walk(go_dir, allocator);
    defer source_walker.deinit();
    while (try source_walker.next(io)) |entry| {
        if (entry.kind != .file or !std.mem.endsWith(u8, entry.path, ".go")) continue;
        if (std.mem.eql(u8, std.fs.path.basename(entry.path), volatile_cgo_link_file)) continue;
        generated.access(io, entry.path, .{}) catch |err| switch (err) {
            error.FileNotFound => {
                const source = try go_dir.readFileAlloc(io, entry.path, allocator, .limited(64 * 1024 * 1024));
                defer allocator.free(source);
                if (std.mem.startsWith(u8, source, generated_marker))
                    try append(allocator, &result, .obsolete, entry.path);
            },
            else => return err,
        };
    }
    std.mem.sort(Difference, result.differences.items, {}, struct {
        fn lessThan(_: void, lhs: Difference, rhs: Difference) bool {
            return std.mem.lessThan(u8, lhs.path, rhs.path);
        }
    }.lessThan);
    return result;
}

/// Compare one generated file that lives outside the Go directory (the
/// `semantic.json` and `errors.lock.json` the update step copies next to the
/// bindings) with its committed copy. The difference is reported under
/// `label`, the path the consumer would commit.
pub fn compareFile(
    allocator: std.mem.Allocator,
    io: std.Io,
    result: *Result,
    generated: std.Io.Dir,
    generated_path: []const u8,
    source: std.Io.Dir,
    source_path: []const u8,
    label: []const u8,
) !void {
    const expected = try generated.readFileAlloc(io, generated_path, allocator, .limited(64 * 1024 * 1024));
    defer allocator.free(expected);
    const actual = source.readFileAlloc(io, source_path, allocator, .limited(64 * 1024 * 1024)) catch |err| switch (err) {
        error.FileNotFound => return append(allocator, result, .missing, label),
        else => return err,
    };
    defer allocator.free(actual);
    if (!std.mem.eql(u8, expected, actual)) try append(allocator, result, .content, label);
}

fn append(allocator: std.mem.Allocator, result: *Result, kind: DifferenceKind, path: []const u8) !void {
    const owned_path = try allocator.dupe(u8, path);
    errdefer allocator.free(owned_path);
    try result.differences.append(allocator, .{ .kind = kind, .path = owned_path });
}

test "source check reports a changed generated Go file" {
    var generated = std.testing.tmpDir(.{ .iterate = true });
    defer generated.cleanup();
    var source = std.testing.tmpDir(.{ .iterate = true });
    defer source.cleanup();
    try generated.dir.createDirPath(std.testing.io, "nested");
    try source.dir.createDirPath(std.testing.io, "nested");
    try generated.dir.writeFile(std.testing.io, .{ .sub_path = "nested/nested_gen.go", .data = "current\n" });
    try source.dir.writeFile(std.testing.io, .{ .sub_path = "nested/nested_gen.go", .data = "edited\n" });
    try source.dir.writeFile(std.testing.io, .{ .sub_path = "nested/user.go", .data = "package nested\n" });
    var result = try compare(std.testing.allocator, std.testing.io, generated.dir, source.dir);
    defer result.deinit(std.testing.allocator);
    try std.testing.expectEqual(@as(usize, 1), result.differences.items.len);
    try std.testing.expectEqualStrings("nested/nested_gen.go", result.differences.items[0].path);
}

test "source check reports obsolete zigo files but ignores user Go files" {
    var generated = std.testing.tmpDir(.{ .iterate = true });
    defer generated.cleanup();
    var source = std.testing.tmpDir(.{ .iterate = true });
    defer source.cleanup();
    try source.dir.createDirPath(std.testing.io, "nested");
    try source.dir.writeFile(std.testing.io, .{
        .sub_path = "nested/obsolete_gen.go",
        .data = generated_marker ++ "\npackage nested\n",
    });
    try source.dir.writeFile(std.testing.io, .{
        .sub_path = "nested/user.go",
        .data = "package nested\n",
    });
    try source.dir.writeFile(std.testing.io, .{
        .sub_path = "nested/zigo_link_inputs_gen.go",
        .data = generated_marker ++ "\npackage nested\n",
    });

    var result = try compare(std.testing.allocator, std.testing.io, generated.dir, source.dir);
    defer result.deinit(std.testing.allocator);
    try std.testing.expectEqual(@as(usize, 1), result.differences.items.len);
    try std.testing.expectEqual(DifferenceKind.obsolete, result.differences.items[0].kind);
    try std.testing.expectEqualStrings("nested/obsolete_gen.go", result.differences.items[0].path);
}

test "source check cleans up every partial allocation failure" {
    var generated = std.testing.tmpDir(.{ .iterate = true });
    defer generated.cleanup();
    var source = std.testing.tmpDir(.{ .iterate = true });
    defer source.cleanup();
    try generated.dir.writeFile(std.testing.io, .{ .sub_path = "changed_gen.go", .data = "current\n" });
    try source.dir.writeFile(std.testing.io, .{ .sub_path = "changed_gen.go", .data = "edited\n" });
    try std.testing.checkAllAllocationFailures(std.testing.allocator, expectChangedSource, .{ generated.dir, source.dir });
}

fn expectChangedSource(allocator: std.mem.Allocator, generated: std.Io.Dir, source: std.Io.Dir) !void {
    var result = try compare(allocator, std.testing.io, generated, source);
    defer result.deinit(allocator);
    try std.testing.expectEqual(@as(usize, 1), result.differences.items.len);
}

