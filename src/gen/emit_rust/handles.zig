//! Opaque handles as owning Rust structs.
//!
//! This is the mapping the feasibility research called the largest win of a
//! Rust target, and it is worth naming what it removes. Go's binding publishes
//! `Close()`, guards every method against having been called after it, and
//! poisons the handle when a native panic escapes -- because a closed handle is
//! still a usable Go value and nothing stops a caller reaching for it. Rust's
//! wrapper owns the native pointer for exactly its own lifetime: the destructor
//! runs in `Drop`, so there is no `Close` to forget, and there is no
//! use-after-close to check for because the borrow checker has already
//! rejected it. The `-4` invalid-handle code the ABI can report is therefore
//! unreachable here, which is why a method with no declared Zig error set
//! returns its value rather than a `Result`.
const std = @import("std");
const abi = @import("abi");
const semantic = @import("semantic");
const buffers = @import("buffers.zig");
const emit = @import("../emit/emit.zig");
const public = @import("public.zig");
const raw = @import("raw.zig");
const types = @import("types.zig");

/// Whether the crate has a handle module at all.
pub fn hasHandles(program: abi.Program) bool {
    for (program.handles) |handle| {
        if (types.renderableHandle(program, handle.name) != null) return true;
    }
    return false;
}

pub fn renderHandles(allocator: std.mem.Allocator, writer: *std.Io.Writer, program: abi.Program, _: emit.Options) !void {
    try writer.writeAll(
        "// Code generated by zigo. DO NOT EDIT.\n\n" ++
            "//! The native objects this binding hands out, each owning its own\n" ++
            "//! lifetime.\n\n" ++
            "use crate::raw;\n",
    );
    if (program.error_codes.len != 0) try writer.writeAll("use crate::Error;\n");
    // A method can hand over a caller-owned buffer, and the owning slice is
    // declared in its own module. Imported by name rather than with a glob so
    // an unused import is a warning `-D warnings` catches.
    if (buffers.hasBuffers(program)) try writer.print("use crate::{s};\n", .{buffers.type_name});
    for (program.handles) |handle| {
        const renderable = types.renderableHandle(program, handle.name) orelse continue;
        try renderHandle(allocator, writer, program, handle, renderable.kind);
    }
}

fn renderHandle(
    allocator: std.mem.Allocator,
    writer: *std.Io.Writer,
    program: abi.Program,
    handle: abi.AbiOpaque,
    kind: types.HandleKind,
) !void {
    const declaration = semantic.typeDecl(program.types, handle.name);
    try writer.writeByte('\n');
    if (declaration) |value| if (value.doc) |doc| try public.writeDocComment(writer, doc, "///");
    switch (kind) {
        .owned => try writer.print(
            \\/// Owns a native `{0s}`.
            \\///
            \\/// The native object is released when this value is dropped, so there is
            \\/// no close call to make and no closed state to guard against.
            \\///
            \\/// Neither `Send` nor `Sync`, which is the honest default: whether the
            \\/// bound library's `{0s}` may cross threads is a fact about that library
            \\/// and zigo does not record it. Wrap it yourself if you know the answer.
            \\pub struct {0s} {{
            \\    pub(crate) handle: *mut raw::{1s},
            \\}}
            \\
            \\impl {0s} {{
        , .{ handle.name, handle.c_name }),
        // A view owns nothing, so it has no `Drop`; what it has is a lifetime.
        // `PhantomData<&'owner ()>` rather than `&'owner Owner` so the view
        // borrows the *lifetime* without also claiming to hold a reference to
        // a particular type -- which would force the owner's name into this
        // struct and make a view borrowable from only one type.
        .borrowed => try writer.print(
            \\/// A borrowed view into a native `{0s}`.
            \\///
            \\/// The lifetime is the borrow of whatever handed this out, so the
            \\/// compiler rejects a view that outlives its owner. Go's binding can
            \\/// only say so in a doc comment and check it at run time.
            \\///
            \\/// Nothing is released when this value is dropped: it points into an
            \\/// object another handle owns.
            \\pub struct {0s}<'owner> {{
            \\    pub(crate) handle: *mut raw::{1s},
            \\    pub(crate) owner: core::marker::PhantomData<&'owner ()>,
            \\}}
            \\
            \\impl {0s}<'_> {{
        , .{ handle.name, handle.c_name }),
    }

    // The constructor first, then the methods in program order, because that
    // is the order a reader of the Zig container met them in.
    for (program.functions) |function| {
        const placement = types.placementOf(program, function);
        if (placement != .constructor or !std.mem.eql(u8, placement.constructor, handle.name)) continue;
        try renderAssociated(allocator, writer, program, function, false);
    }
    for (program.functions) |function| {
        const placement = types.placementOf(program, function);
        if (placement != .method or !std.mem.eql(u8, placement.method, handle.name)) continue;
        try renderAssociated(allocator, writer, program, function, true);
    }
    try writer.writeAll("}\n");
    // A view has nothing to release, so it has no `Drop` -- which is the whole
    // difference between the two kinds.
    if (kind == .owned) try renderDrop(allocator, writer, program, handle);
}

/// One associated function: a method when `is_method`, a constructor
/// otherwise. Both go through `public.writeBody`, so the status-code rule and
/// the result shape cannot differ between a method and a free function.
fn renderAssociated(
    allocator: std.mem.Allocator,
    writer: *std.Io.Writer,
    program: abi.Program,
    function: abi.AbiFn,
    is_method: bool,
) !void {
    const shape = try raw.Shape.of(allocator, program, function);
    defer shape.deinit(allocator);
    const name = if (is_method)
        try allocator.dupe(u8, shape.public_name)
    else
        try constructorNameAlloc(allocator, program, function);
    defer allocator.free(name);
    try writer.writeByte('\n');
    var documented = false;
    if (function.origin.doc) |doc| {
        try public.writeDocComment(writer, doc, "    ///");
        documented = true;
    }
    if (function.errors.len != 0) {
        // The blank doc line only separates two paragraphs, so it is written
        // only when there is a first one to separate from.
        if (documented) try writer.writeAll("    ///\n");
        try writer.writeAll("    /// # Errors\n    ///\n");
        for (function.errors) |code| try writer.print("    /// - [`ErrorKind::{s}`]\n", .{code.name});
    }
    try writer.print("    pub fn {s}(", .{name});
    try public.writeParameters(writer, shape, if (shape.receiver) |record| record.publicSelf() else null);
    try writer.writeByte(')');
    try public.writePublicResultType(writer, shape);
    try writer.writeAll(" {\n    ");
    // The body is written at the module's indentation and re-indented here,
    // rather than being written twice at two indentations. `rustfmt` would
    // settle the layout either way; keeping one writer keeps the *logic* in
    // one place, which is the part that could go wrong.
    var body: std.Io.Writer.Allocating = .init(allocator);
    defer body.deinit();
    try public.writeBody(allocator, &body.writer, shape, function, if (shape.receiver != null) "self.handle" else null);
    var lines = std.mem.splitScalar(u8, std.mem.trimEnd(u8, body.written(), "\n"), '\n');
    var first = true;
    while (lines.next()) |line| {
        if (!first) try writer.writeAll("    ");
        first = false;
        try writer.print("{s}\n", .{line});
    }
    try writer.writeAll("    }\n");
}

fn constructorNameAlloc(allocator: std.mem.Allocator, program: abi.Program, function: abi.AbiFn) ![]u8 {
    const rust = @import("targets").rust;
    const constructor = semantic.constructorForInit(program.constructors, function.origin.*).?;
    return rust.constructorNameAlloc(allocator, constructor.type, constructor.name);
}

/// The whole point, in eight lines.
///
/// The destructor's status code is deliberately discarded. `Drop` cannot
/// return, and it must not panic: a panic while another panic is unwinding
/// aborts the process, so a destructor that reported a caught native panic by
/// panicking would turn a recoverable failure into an abort. Go's `Close()`
/// returns an error and leaves the caller to ignore it; this ignores it once,
/// here, where the reason can be written down.
fn renderDrop(
    allocator: std.mem.Allocator,
    writer: *std.Io.Writer,
    program: abi.Program,
    handle: abi.AbiOpaque,
) !void {
    const function = destructorFor(program, handle) orelse return error.MissingDestructor;
    // Through the raw wrapper, not the `extern` symbol: the wrapper is where
    // the `unsafe` block lives, so nothing in this file needs one.
    const shape = try raw.Shape.of(allocator, program, function);
    defer shape.deinit(allocator);
    const destructor = shape.raw_name;
    try writer.print(
        \\
        \\impl Drop for {0s} {{
        \\    fn drop(&mut self) {{
        \\        // The status code is dropped on purpose: `Drop` cannot return
        \\        // it, and panicking here would abort the process whenever a
        \\        // destructor failed during another panic's unwind.
        \\        let _ = unsafe {{ raw::{1s}(self.handle) }};
        \\    }}
        \\}}
        \\
    , .{ handle.name, destructor });
}

/// The handle's destructor, as one of `program.functions`.
fn destructorFor(program: abi.Program, handle: abi.AbiOpaque) ?abi.AbiFn {
    for (program.functions) |function| {
        const placement = types.placementOf(program, function);
        if (placement != .destructor or !std.mem.eql(u8, placement.destructor, handle.name)) continue;
        return function;
    }
    return null;
}
