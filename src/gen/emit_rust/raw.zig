//! The raw Rust module: the `extern "C"` block over the shim's exports, and
//! one safe-signature wrapper per bound function that does the marshalling.
//!
//! The split mirrors the Go raw package's job -- turn the C calling convention
//! into something the public layer can call without thinking about pointers --
//! but it shares no code with it. What the two do share is the C header this
//! block declares, which is why the symbols and their order here come straight
//! off `program.functions`, exactly as `emit/header.zig` reads them.
const std = @import("std");
const abi = @import("abi");
const semantic = @import("semantic");
const emit = @import("../emit/emit.zig");
// The Rust target's own rules, reached the way the Go emitter reaches Go's:
// through the `targets` module, since `targets.zig` owns those files.
const rust = @import("targets").rust;
const words = rust.words;
const types = @import("types.zig");

pub fn renderRaw(allocator: std.mem.Allocator, writer: *std.Io.Writer, program: abi.Program, _: emit.Options) !void {
    try writer.writeAll(
        "// Code generated by zigo. DO NOT EDIT.\n\n" ++
            "//! The generated call layer between the public API and the native\n" ++
            "//! library. Not part of the supported API.\n\n" ++
            "#![allow(dead_code)]\n\n" ++
            "use core::ffi::c_char;\n\n",
    );
    try renderExternBlock(allocator, writer, program);
    try renderMessageAccessors(writer, program);
    for (program.functions) |function| {
        if (types.unsupported(program, function) != null) continue;
        try renderWrapper(allocator, writer, program, function);
    }
}

/// The `extern "C"` block, one declaration per exported symbol in the order
/// the header declares them. Edition 2021 spells the block without the `unsafe`
/// qualifier that edition 2024 requires.
fn renderExternBlock(allocator: std.mem.Allocator, writer: *std.Io.Writer, program: abi.Program) !void {
    try writer.writeAll("extern \"C\" {\n");
    for (program.functions) |function| {
        if (types.unsupported(program, function) != null) continue;
        try writer.print("    pub fn {s}(", .{function.symbol});
        for (function.params, 0..) |parameter, index| {
            if (index != 0) try writer.writeAll(", ");
            const name = try parameterNameAlloc(allocator, parameter);
            defer allocator.free(name);
            try writer.print("{s}: ", .{name});
            try writeRawParamType(writer, parameter);
        }
        try writer.writeByte(')');
        // Rust writes no return type for `()`, and `clippy` objects when one
        // is written, so `void` is the absence of the arrow rather than `-> ()`.
        if (function.ret != .void) {
            try writer.writeAll(" -> ");
            try writer.writeAll(types.rawScalar(function.ret) orelse return error.UnsupportedType);
        }
        try writer.writeAll(";\n");
    }
    // The two message accessors every binding exports, declared last exactly
    // as the header declares them.
    try writer.print("    pub fn {s}_last_error_message() -> *const c_char;\n", .{program.prefix});
    try writer.print("    pub fn {s}_caught_panic_message(code: i32) -> *const c_char;\n", .{program.prefix});
    try writer.writeAll("}\n");
}

/// The C parameter name, made a legal Rust binding. The names come from
/// lowering and are already snake_case, so this is only the keyword escape:
/// a Zig parameter named `type` reaches here as `type`, which Rust reserves.
fn parameterNameAlloc(allocator: std.mem.Allocator, parameter: abi.AbiParam) ![]u8 {
    if (!words.isKeyword(parameter.name)) return allocator.dupe(u8, parameter.name);
    if (words.isRawIdentifierEligible(parameter.name))
        return std.fmt.allocPrint(allocator, "r#{s}", .{parameter.name});
    return std.fmt.allocPrint(allocator, "{s}_", .{parameter.name});
}

fn writeRawParamType(writer: *std.Io.Writer, parameter: abi.AbiParam) !void {
    switch (parameter.role) {
        .slice_pointer, .string_data => {
            const pointer = parameter.scalar.pointer;
            try writer.print("*{s} ", .{if (pointer.is_const) "const" else "mut"});
            try writer.writeAll(types.rawScalar(pointer.child.*) orelse return error.UnsupportedType);
        },
        // The out-parameter pair a fallible or slice-returning call writes
        // through. `payload_out` carries one value; the two `return_slice_*`
        // roles carry a pointer and a length, so the pointer's own parameter
        // is a pointer to a pointer.
        .payload_out, .return_slice_pointer, .return_slice_length => {
            const pointer = parameter.scalar.pointer;
            try writer.writeAll("*mut ");
            try writeRawPointee(writer, pointer.child.*, pointer.is_many);
        },
        else => try writer.writeAll(types.rawScalar(parameter.scalar) orelse return error.UnsupportedType),
    }
}

fn writeRawPointee(writer: *std.Io.Writer, child: abi.AbiScalar, is_many: bool) !void {
    if (child == .pointer) {
        const inner = child.pointer;
        try writer.print("*{s} ", .{if (inner.is_const) "const" else "mut"});
        return writer.writeAll(types.rawScalar(inner.child.*) orelse return error.UnsupportedType);
    }
    _ = is_many;
    try writer.writeAll(types.rawScalar(child) orelse return error.UnsupportedType);
}

/// The two panic-message readers. Both cross as `const char *`, so both go
/// through `CStr`, which is the only place this module reads native memory it
/// does not own -- the shim keeps both strings alive for the process.
fn renderMessageAccessors(writer: *std.Io.Writer, program: abi.Program) !void {
    try writer.print(
        \\
        \\/// The most recent native panic message for this binding.
        \\pub fn last_error_message() -> String {{
        \\    unsafe {{ message_at({0s}_last_error_message()) }}
        \\}}
        \\
        \\/// The message of the native panic a status code of -256 or below names.
        \\pub fn panic_message(code: i32) -> String {{
        \\    unsafe {{ message_at({0s}_caught_panic_message(code)) }}
        \\}}
        \\
        \\/// Copies a NUL-terminated message the shim owns. A null pointer is an
        \\/// absent message rather than an error: the accessors return one when no
        \\/// panic has been recorded.
        \\///
        \\/// # Safety
        \\///
        \\/// `pointer` must be null or point at a NUL-terminated string that stays
        \\/// valid for the duration of the call.
        \\unsafe fn message_at(pointer: *const c_char) -> String {{
        \\    if pointer.is_null() {{
        \\        return String::new();
        \\    }}
        \\    unsafe {{ core::ffi::CStr::from_ptr(pointer) }}
        \\        .to_string_lossy()
        \\        .into_owned()
        \\}}
        \\
    , .{program.prefix});
}

/// One wrapper per bound function: the unsafe call, with the slice and
/// out-parameter mechanics on this side of it so the public layer holds no
/// `unsafe`.
///
/// The wrapper's return shape is the call's ABI shape, not its public shape:
/// a fallible function returns `(payload, code)` and the public layer turns
/// the code into a `Result`. Keeping the split there means the error type is
/// the public layer's business alone.
fn renderWrapper(
    allocator: std.mem.Allocator,
    writer: *std.Io.Writer,
    program: abi.Program,
    function: abi.AbiFn,
) !void {
    const shape = try Shape.of(allocator, program, function);
    defer shape.deinit(allocator);
    try writer.print("\n/// Calls the generated C ABI wrapper for `{s}`.\n", .{function.symbol});
    try writer.print("pub fn {s}(", .{shape.raw_name});
    for (shape.inputs, 0..) |input, index| {
        if (index != 0) try writer.writeAll(", ");
        try writer.print("{s}: ", .{input.name});
        try input.writeRawType(writer);
    }
    try writer.writeByte(')');
    try shape.writeRawResultType(writer);
    try writer.writeAll(" {\n");
    // Declare the out parameters before the call, since the call takes their
    // addresses.
    if (shape.payload) |payload| switch (payload) {
        // A literal zero rather than `Default::default()`: the value is
        // overwritten by the call, so the initializer only has to be a valid
        // one, and a concrete literal reads as the placeholder it is.
        .scalar => |scalar| try writer.print("    let mut out_result: {s} = {s};\n", .{
            scalar,
            if (scalar.len != 0 and scalar[0] == 'f') "0.0" else "0",
        }),
        .slice => |element| try writer.print(
            "    let mut out_result_ptr: *const {s} = core::ptr::null();\n    let mut out_result_len: usize = 0;\n",
            .{element.raw},
        ),
    };
    // The call is the tail expression whenever nothing has to be read after
    // it. Binding it to a name first and returning the name is what `clippy`
    // calls `let_and_return`, and it would be the shape of every infallible
    // scalar call -- which is most of them.
    // Only an out parameter has to be read after the call. A fallible call
    // with no payload returns its status code and nothing else, so that too
    // is the tail expression.
    const binds_code = shape.payload != null;
    try writer.writeAll("    ");
    if (binds_code) try writer.writeAll("let code = ");
    try writer.print("unsafe {{ {s}(", .{function.symbol});
    for (function.params, 0..) |parameter, index| {
        if (index != 0) try writer.writeAll(", ");
        try writeArgument(writer, shape, parameter);
    }
    try writer.writeAll(if (binds_code) ") };\n" else ") }\n");
    try shape.writeRawReturn(writer);
    try writer.writeAll("}\n");
}

fn writeArgument(writer: *std.Io.Writer, shape: Shape, parameter: abi.AbiParam) !void {
    switch (parameter.role) {
        .slice_pointer, .string_data => {
            const input = shape.inputFor(parameter.source_index).?;
            // An empty Rust slice still yields a non-null, aligned pointer, so
            // there is no zero-slot dance here: `[]const T` in Zig wants
            // exactly what `as_ptr` guarantees. Go needs a placeholder
            // variable for this; Rust's slice representation already answers it.
            // `&str` and `&[T]` both answer `as_ptr`, and `&str`'s answer is
            // already `*const u8`, which is what the C signature asks for.
            try writer.print("{s}.as_ptr()", .{input.name});
        },
        .slice_length, .string_data_length => {
            const input = shape.inputFor(parameter.source_index).?;
            try writer.print("{s}.len()", .{input.name});
        },
        .payload_out => try writer.writeAll("&mut out_result"),
        .return_slice_pointer => try writer.writeAll("&mut out_result_ptr"),
        .return_slice_length => try writer.writeAll("&mut out_result_len"),
        else => {
            const input = shape.inputFor(parameter.source_index).?;
            if (input.is_bool) try writer.print("u8::from({s})", .{input.name}) else try writer.writeAll(input.name);
        },
    }
}

/// One function's shape as both layers need to see it: its Rust name, its
/// public inputs, and how its result travels. Computed once so the raw
/// wrapper and the public wrapper cannot disagree about a name or an order.
pub const Shape = struct {
    /// Snake-case name, shared by the raw wrapper and the public function.
    raw_name: []u8,
    inputs: []Input,
    /// Present when the result travels through an out parameter.
    payload: ?Payload = null,
    /// The scalar the call returns directly, when it returns one and it is not
    /// a status code.
    direct: ?Direct = null,
    /// The function can fail, so its C return is a status code.
    fallible: bool,

    pub const Direct = struct { raw: []const u8, public: []const u8, is_bool: bool };

    pub const Payload = union(enum) {
        scalar: []const u8,
        slice: types.Element,
    };

    pub const Input = struct {
        name: []u8,
        source_index: usize,
        /// Null for a slice input, whose spelling is the element plus a
        /// pointer-and-length pair.
        scalar: ?[]const u8 = null,
        element: ?types.Element = null,
        is_bool: bool = false,
        text: bool = false,

        pub fn writeRawType(self: Input, writer: *std.Io.Writer) !void {
            if (self.element) |element| {
                if (self.text) return writer.writeAll("&str");
                return writer.print("&[{s}]", .{element.raw});
            }
            try writer.writeAll(self.scalar.?);
        }
    };

    pub fn of(allocator: std.mem.Allocator, program: abi.Program, function: abi.AbiFn) !Shape {
        const origin = function.origin.*;
        const raw_name = try rust.target.exportedFunctionNameAlloc(allocator, origin.name);
        errdefer allocator.free(raw_name);
        const zig_names = try allocator.alloc([]const u8, origin.params.len);
        defer allocator.free(zig_names);
        for (origin.params, zig_names) |parameter, *name| name.* = parameter.name;
        // The names are moved into `inputs` below, so only the outer slice is
        // released here; `Shape.deinit` owns the strings.
        const names = try rust.paramNamesAlloc(allocator, zig_names);
        defer allocator.free(names);
        errdefer for (names) |name| allocator.free(name);
        var inputs: std.ArrayList(Input) = .empty;
        errdefer inputs.deinit(allocator);
        for (origin.params, names, 0..) |parameter, name, index| {
            var input: Input = .{ .name = name, .source_index = index };
            switch (parameter.type) {
                .slice => {
                    input.element = types.sliceElement(program, parameter.type, function.paramString(index).role) orelse
                        return error.UnsupportedType;
                    input.text = input.element.?.text;
                },
                .bool => {
                    input.scalar = "bool";
                    input.is_bool = true;
                },
                else => input.scalar = types.publicScalar(
                    parameter.type,
                    @import("../emit/type_spelling.zig").semanticScalar(program, parameter.type),
                ) orelse return error.UnsupportedType,
            }
            try inputs.append(allocator, input);
        }
        const fallible = origin.@"return" == .error_union;
        const payload_node: semantic.TypeNode = if (fallible) origin.@"return".error_union.payload.* else origin.@"return";
        var shape: Shape = .{
            .raw_name = raw_name,
            .inputs = try inputs.toOwnedSlice(allocator),
            .fallible = fallible,
        };
        if (payload_node == .slice) {
            shape.payload = .{ .slice = types.sliceElement(program, payload_node, function.ret_string) orelse
                return error.UnsupportedType };
        } else if (fallible and payload_node != .void) {
            shape.payload = .{ .scalar = types.rawScalar(
                @import("../emit/type_spelling.zig").semanticScalar(program, payload_node),
            ) orelse return error.UnsupportedType };
        } else if (!fallible and payload_node != .void) {
            const scalar = @import("../emit/type_spelling.zig").semanticScalar(program, payload_node);
            shape.direct = .{
                .raw = types.rawScalar(scalar) orelse return error.UnsupportedType,
                .public = types.publicScalar(payload_node, scalar) orelse return error.UnsupportedType,
                .is_bool = payload_node == .bool,
            };
        }
        return shape;
    }

    pub fn deinit(self: Shape, allocator: std.mem.Allocator) void {
        allocator.free(self.raw_name);
        for (self.inputs) |input| allocator.free(input.name);
        allocator.free(self.inputs);
    }

    pub fn inputFor(self: Shape, source_index: usize) ?Input {
        for (self.inputs) |input| if (input.source_index == source_index) return input;
        return null;
    }

    /// The raw wrapper's return type: the payload beside its status code when
    /// the call can fail, the payload alone when it cannot.
    pub fn writeRawResultType(self: Shape, writer: *std.Io.Writer) !void {
        if (self.payload) |payload| {
            try writer.writeAll(" -> (");
            switch (payload) {
                .scalar => |scalar| try writer.writeAll(scalar),
                .slice => |element| try writer.print("*const {s}, usize", .{element.raw}),
            }
            if (self.fallible) try writer.writeAll(", i32");
            return writer.writeByte(')');
        }
        if (self.fallible) return writer.writeAll(" -> i32");
        if (self.direct) |direct| return writer.print(" -> {s}", .{direct.raw});
    }

    pub fn writeRawReturn(self: Shape, writer: *std.Io.Writer) !void {
        if (self.payload) |payload| {
            try writer.writeAll("    (");
            switch (payload) {
                .scalar => try writer.writeAll("out_result"),
                .slice => try writer.writeAll("out_result_ptr, out_result_len"),
            }
            if (self.fallible) try writer.writeAll(", code");
            return writer.writeAll(")\n");
        }
    }
};
