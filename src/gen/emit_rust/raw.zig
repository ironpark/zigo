//! The raw Rust module: the `extern "C"` block over the shim's exports, and
//! one safe-signature wrapper per bound function that does the marshalling.
//!
//! The split mirrors the Go raw package's job -- turn the C calling convention
//! into something the public layer can call without thinking about pointers --
//! but it shares no code with it. What the two do share is the C header this
//! block declares, which is why the symbols and their order here come straight
//! off `program.functions`, exactly as `emit/header.zig` reads them.
const std = @import("std");
const abi = @import("abi");
const semantic = @import("semantic");
const emit = @import("../emit/emit.zig");
const type_spelling = @import("../emit/type_spelling.zig");
// The Rust target's own rules, reached the way the Go emitter reaches Go's:
// through the `targets` module, since `targets.zig` owns those files.
const rust = @import("targets").rust;
const words = rust.words;
const types = @import("types.zig");

pub fn renderRaw(allocator: std.mem.Allocator, writer: *std.Io.Writer, program: abi.Program, _: emit.Options) !void {
    try writer.writeAll(
        "// Code generated by zigo. DO NOT EDIT.\n\n" ++
            "//! The generated call layer between the public API and the native\n" ++
            "//! library. Not part of the supported API.\n\n" ++
            "#![allow(dead_code)]\n" ++
            "// An `unsafe fn` body is implicitly unsafe in edition 2021, which would\n" ++
            "// make the block inside one redundant. Denying that keeps every native\n" ++
            "// call inside an explicit block, so the unsafe operations stay visible.\n" ++
            "#![deny(unsafe_op_in_unsafe_fn)]\n\n" ++
            "use core::ffi::c_char;\n\n",
    );
    // The incomplete C structs the signatures below point at, before the
    // block that names them.
    for (program.handles) |handle| {
        if (types.renderableHandle(program, handle.name) == null) continue;
        try types.opaqueDeclaration(writer, handle);
    }
    try renderExternBlock(allocator, writer, program);
    try renderMessageAccessors(writer, program);
    // No `unsupported` check here: `generator.appendRustCrate` refuses the
    // whole document before any emitter runs, so a function that reaches this
    // loop is one this backend can render. A skip here would make the emitter
    // a filtering pass, which is the silent omission ZIGO060 exists to prevent.
    for (program.functions) |function| try renderWrapper(allocator, writer, program, function);
}

/// The `extern "C"` block, one declaration per exported symbol in the order
/// the header declares them. Edition 2021 spells the block without the `unsafe`
/// qualifier that edition 2024 requires.
fn renderExternBlock(allocator: std.mem.Allocator, writer: *std.Io.Writer, program: abi.Program) !void {
    try writer.writeAll("extern \"C\" {\n");
    for (program.functions) |function| {
        try writer.print("    pub fn {s}(", .{function.symbol});
        for (function.params, 0..) |parameter, index| {
            if (index != 0) try writer.writeAll(", ");
            const name = try parameterNameAlloc(allocator, parameter);
            defer allocator.free(name);
            try writer.print("{s}: ", .{name});
            try writeRawParamType(writer, parameter);
        }
        try writer.writeByte(')');
        // Rust writes no return type for `()`, and `clippy` objects when one
        // is written, so `void` is the absence of the arrow rather than `-> ()`.
        if (function.ret != .void) {
            try writer.writeAll(" -> ");
            try writer.writeAll(types.rawScalar(function.ret) orelse return error.UnsupportedType);
        }
        try writer.writeAll(";\n");
    }
    // The two message accessors every binding exports, declared last exactly
    // as the header declares them.
    try writer.print("    pub fn {s}_last_error_message() -> *const c_char;\n", .{program.prefix});
    try writer.print("    pub fn {s}_caught_panic_message(code: i32) -> *const c_char;\n", .{program.prefix});
    try writer.writeAll("}\n");
}

/// The C parameter name, made a legal Rust binding. The names come from
/// lowering and are already snake_case, so this is only the keyword escape:
/// a Zig parameter named `type` reaches here as `type`, which Rust reserves.
fn parameterNameAlloc(allocator: std.mem.Allocator, parameter: abi.AbiParam) ![]u8 {
    if (!words.isKeyword(parameter.name)) return allocator.dupe(u8, parameter.name);
    if (words.isRawIdentifierEligible(parameter.name))
        return std.fmt.allocPrint(allocator, "r#{s}", .{parameter.name});
    return std.fmt.allocPrint(allocator, "{s}_", .{parameter.name});
}

fn writeRawParamType(writer: *std.Io.Writer, parameter: abi.AbiParam) !void {
    // Every role's spelling is the scalar lowering already recorded, pointers
    // and all. The roles used to be spelled one by one here, which meant the
    // handle roles had nothing to answer with.
    return types.writeRawScalar(writer, parameter.scalar);
}

/// The two panic-message readers. Both cross as `const char *`, so both go
/// through `CStr`, which is the only place this module reads native memory it
/// does not own -- the shim keeps both strings alive for the process.
fn renderMessageAccessors(writer: *std.Io.Writer, program: abi.Program) !void {
    try writer.print(
        \\
        \\/// The most recent native panic message for this binding.
        \\pub fn last_error_message() -> String {{
        \\    unsafe {{ message_at({0s}_last_error_message()) }}
        \\}}
        \\
        \\/// The message of the native panic a status code of -256 or below names.
        \\pub fn panic_message(code: i32) -> String {{
        \\    unsafe {{ message_at({0s}_caught_panic_message(code)) }}
        \\}}
        \\
        \\/// Reports a native failure the call had no error channel for.
        \\///
        \\/// Only two codes can reach here. `-4` is an invalid handle, which a
        \\/// generated wrapper makes unreachable by owning a non-null pointer for
        \\/// its whole life -- Go needs a run-time check for it because a closed
        \\/// handle is still a usable Go value. `-256` and below is a Zig panic the
        \\/// shim caught. Both are defects in the bound library rather than
        \\/// conditions a caller can act on, and Rust's vehicle for a defect in the
        \\/// callee is a panic, so a call whose Zig signature declares no error set
        \\/// returns its value directly and comes here if the native side failed.
        \\///
        \\/// Declare a Zig error set on the function to get a `Result` instead.
        \\#[cold]
        \\pub fn panic_native(operation: &str, code: i32) -> ! {{
        \\    let message = panic_message(code);
        \\    if message.is_empty() {{
        \\        panic!("zigo: {{operation}}: native failure, status {{code}}");
        \\    }}
        \\    panic!("zigo: {{operation}}: native panic: {{message}}");
        \\}}
        \\
        \\/// Copies a NUL-terminated message the shim owns. A null pointer is an
        \\/// absent message rather than an error: the accessors return one when no
        \\/// panic has been recorded.
        \\///
        \\/// # Safety
        \\///
        \\/// `pointer` must be null or point at a NUL-terminated string that stays
        \\/// valid for the duration of the call.
        \\unsafe fn message_at(pointer: *const c_char) -> String {{
        \\    if pointer.is_null() {{
        \\        return String::new();
        \\    }}
        \\    unsafe {{ core::ffi::CStr::from_ptr(pointer) }}
        \\        .to_string_lossy()
        \\        .into_owned()
        \\}}
        \\
    , .{program.prefix});
}

/// One wrapper per bound function: the unsafe call, with the slice and
/// out-parameter mechanics on this side of it so the public layer holds no
/// `unsafe`.
///
/// The wrapper's return shape is the call's ABI shape, not its public shape:
/// a call with a status channel returns `(payload, code)` and the public layer
/// decides what a non-zero code means. Keeping the split there means both the
/// error type and the panic are the public layer's business alone.
fn renderWrapper(
    allocator: std.mem.Allocator,
    writer: *std.Io.Writer,
    program: abi.Program,
    function: abi.AbiFn,
) !void {
    const shape = try Shape.of(allocator, program, function);
    defer shape.deinit(allocator);
    try writer.print("\n/// Calls the generated C ABI wrapper for `{s}`.\n", .{function.symbol});
    const unsafe_wrapper = shape.touchesHandlePointer();
    if (unsafe_wrapper) try writer.writeAll(
        "///\n" ++
            "/// # Safety\n" ++
            "///\n" ++
            "/// Every handle argument must point at a live native object of its own\n" ++
            "/// type. The generated wrapper that owns the handle guarantees this; a\n" ++
            "/// hand-written caller has to.\n",
    );
    try writer.print("pub {s}fn {s}(", .{ if (unsafe_wrapper) "unsafe " else "", shape.raw_name });
    var written = false;
    if (shape.receiver) |record| {
        try writer.print("{s}: *{s} {s}", .{
            receiver_parameter,
            if (record.is_const) "const" else "mut",
            record.c_name,
        });
        written = true;
    }
    for (shape.inputs) |input| {
        if (input.injected) continue;
        if (written) try writer.writeAll(", ");
        written = true;
        try writer.print("{s}: ", .{input.name});
        try input.writeRawType(writer);
    }
    try writer.writeByte(')');
    try shape.writeRawResultType(writer);
    try writer.writeAll(" {\n");
    // Declare the out parameters before the call, since the call takes their
    // addresses.
    if (shape.payload) |payload| switch (payload) {
        // A literal zero rather than `Default::default()`: the value is
        // overwritten by the call, so the initializer only has to be a valid
        // one, and a concrete literal reads as the placeholder it is.
        .scalar => |scalar| try writer.print("    let mut out_result: {s} = {s};\n", .{
            scalar.raw,
            if (scalar.raw.len != 0 and scalar.raw[0] == 'f') "0.0" else "0",
        }),
        .slice => |element| try writer.print(
            "    let mut out_result_ptr: *const {s} = core::ptr::null();\n    let mut out_result_len: usize = 0;\n",
            .{element.raw},
        ),
        .buffer => |buffer| try writer.print(
            "    let mut out_result_ptr: *const {s} = core::ptr::null();\n    let mut out_result_len: usize = 0;\n",
            .{buffer.element.raw},
        ),
        // A null placeholder the call overwrites. The public wrapper checks it
        // rather than trusting the status code alone, because a constructor
        // that reported success and wrote nothing would otherwise produce a
        // wrapper whose `Drop` frees a null pointer.
        .handle => |record| try writer.print(
            "    let mut out_result: *mut {s} = core::ptr::null_mut();\n",
            .{record.c_name},
        ),
    };
    // The call is the tail expression whenever nothing has to be read after
    // it. Binding it to a name first and returning the name is what `clippy`
    // calls `let_and_return`, and it would be the shape of every scalar call
    // with no out parameter -- which is most of them.
    //
    // Being a statement and binding a name are two different questions. A call
    // with an out parameter but no status code is a statement, but the C
    // wrapper returns `void`, so binding `code` to it binds `()` and rustc
    // rejects the unused name under `-D warnings`.
    const reads_after_call = shape.payload != null;
    try writer.writeAll("    ");
    if (reads_after_call and shape.has_status_code) try writer.writeAll("let code = ");
    try writer.print("unsafe {{ {s}(", .{function.symbol});
    for (function.params, 0..) |parameter, index| {
        if (index != 0) try writer.writeAll(", ");
        try writeArgument(writer, shape, parameter);
    }
    try writer.writeAll(if (reads_after_call) ") };\n" else ") }\n");
    try shape.writeRawReturn(writer);
    try writer.writeAll("}\n");
}

/// What the raw wrapper calls its receiver parameter. Not `self`, which is a
/// Rust keyword outside an `impl` block, and not `handle`, which the public
/// wrapper's field is already called.
const receiver_parameter = "receiver";

fn writeArgument(writer: *std.Io.Writer, shape: Shape, parameter: abi.AbiParam) !void {
    switch (parameter.role) {
        .receiver => return writer.writeAll(receiver_parameter),
        .slice_pointer, .string_data => {
            const input = shape.inputs[parameter.source_index];
            // An empty Rust slice still yields a non-null, aligned pointer, so
            // there is no zero-slot dance here: `[]const T` in Zig wants
            // exactly what `as_ptr` guarantees. Go needs a placeholder
            // variable for this; Rust's slice representation already answers it.
            // `&str` and `&[T]` both answer `as_ptr`, and `&str`'s answer is
            // already `*const u8`, which is what the C signature asks for.
            try writer.print("{s}.as_ptr()", .{input.name});
        },
        .slice_length, .string_data_length => {
            const input = shape.inputs[parameter.source_index];
            try writer.print("{s}.len()", .{input.name});
        },
        .payload_out => try writer.writeAll("&mut out_result"),
        .return_slice_pointer => try writer.writeAll("&mut out_result_ptr"),
        .return_slice_length => try writer.writeAll("&mut out_result_len"),
        else => {
            const input = shape.inputs[parameter.source_index];
            if (input.is_bool) try writer.print("u8::from({s})", .{input.name}) else try writer.writeAll(input.name);
        },
    }
}

/// One function's shape as both layers need to see it: its Rust name, its
/// public inputs, and how its result travels. Each layer derives its own from
/// the same function, so the raw wrapper and the public wrapper cannot
/// disagree about a name or an order.
pub const Shape = struct {
    /// The raw wrapper's name, qualified by the owning type when there is one:
    /// `Context.add` reaches the raw module as `context_add`. The raw module
    /// is flat, so an unqualified name would make two types' `add` collide
    /// there -- which is the same reason Go's raw layer spells `ContextAdd`.
    raw_name: []u8,
    /// The public spelling. For a method this is the bare name, because the
    /// `impl` block already says which type it belongs to; for a free function
    /// it is the same as `raw_name`. A constructor's public name is neither --
    /// the target answers it -- so `handles.zig` asks for that one directly.
    public_name: []u8,
    /// The handle a method is called on. Not part of `inputs`, because the
    /// receiver is not in `origin.params` -- Zig declares it, the IR records
    /// it separately, and the public layer spells it `&self` rather than
    /// naming it at all.
    receiver: ?Receiver = null,
    inputs: []Input,
    /// Present when the result travels through an out parameter.
    payload: ?Payload = null,
    /// The scalar the call returns directly, when it returns one and it is not
    /// a status code.
    direct: ?Direct = null,
    /// The C return is a status code rather than the result, so the result
    /// travels through an out parameter and the code has to be inspected.
    ///
    /// This is *not* the same question as `declares_errors` below, and
    /// conflating the two is what made a narrow-integer parameter generate a
    /// crate that referenced an error type nobody emitted.
    /// `lower.promoteCheckedFunctions` rewrites the return of every function
    /// that `reportsPanics` -- a handle receiver, a handle parameter, or a
    /// narrow-integer parameter -- into an error union with an *empty* error
    /// set, because a native panic needs a channel to be reported through.
    /// So a status channel exists far more often than a Zig error does.
    has_status_code: bool,
    /// The binding declares a Zig error set for this call, so a non-zero code
    /// is a condition the caller can act on and the public signature is a
    /// `Result`.
    ///
    /// When this is false but `has_status_code` is true, the only reachable
    /// non-zero codes are `-4` (an invalid handle, which a Rust wrapper makes
    /// unreachable by owning a non-null pointer for its whole life) and
    /// `<= -256` (a caught Zig panic). Both are defects rather than
    /// conditions, and Rust's vehicle for a defect in the callee is a panic,
    /// so the public signature stays the bare payload.
    declares_errors: bool,

    pub const Direct = struct { raw: []const u8, public: []const u8, is_bool: bool };

    pub const Buffer = struct {
        element: types.Element,
        /// The `extern` symbol of the release function, taken by address as
        /// the owning slice's release callback.
        release_symbol: []const u8,
    };

    /// A handle a call produces. Named apart from `Input.Handle`, which is a
    /// handle a call *takes*: the two answer different questions and Zig would
    /// otherwise resolve the bare name ambiguously inside `Input`.
    pub const Produced = struct {
        type_name: []const u8,
        c_name: []const u8,
        kind: types.HandleKind,

        /// The public spelling of the produced value. An owned handle is
        /// `Self` -- so a renamed wrapper cannot drift from its constructor --
        /// and a borrowed one names its type with an inferred lifetime, which
        /// is the receiver's borrow.
        pub fn writePublicType(self: Produced, writer: *std.Io.Writer) !void {
            return switch (self.kind) {
                .owned => writer.writeAll("Self"),
                .borrowed => writer.print("{s}<'_>", .{self.type_name}),
            };
        }
    };

    pub const Receiver = struct {
        /// Registered type name, as the public wrapper struct is called.
        type_name: []const u8,
        /// The incomplete C struct the raw module declares.
        c_name: []const u8,
        /// The C pointer is const, which lowering records only for a
        /// by-value receiver. A Zig `*const T` receiver still crosses as a
        /// non-const pointer, so this is not the `&self`/`&mut self`
        /// question it looks like -- see `Receiver.publicSelf`.
        is_const: bool,

        /// How the public method spells its receiver.
        ///
        /// `&self` for a by-value Zig receiver, `&mut self` otherwise. This is
        /// less precise than Zig, which also distinguishes `*const T` from
        /// `*T`, but that distinction is not in the IR: lowering gives both a
        /// non-const C pointer, so the header for a `*const Context` method
        /// reads `zg_context *self`. `&mut self` where `&self` would do costs
        /// a caller some flexibility and is never unsound, so the
        /// conservative answer is the safe one. Go cannot express either
        /// distinction: every receiver is `*Context`.
        pub fn publicSelf(self: Receiver) []const u8 {
            return if (self.is_const) "&self" else "&mut self";
        }
    };

    pub const Payload = union(enum) {
        /// Both spellings, because the C ABI carries a Zig `bool` as a byte:
        /// the raw layer sees `u8` and only the public layer knows it is a
        /// `bool`. Spelling the payload with the raw name alone made
        /// `error{E}!bool` arrive as `Result<u8, Error>`.
        scalar: Direct,
        slice: types.Element,
        /// A slice the library allocated and handed over. Identical to `slice`
        /// at the ABI -- the same pointer-and-length pair -- and different in
        /// the public layer, which owns it instead of copying it.
        buffer: Buffer,
        /// A constructed or borrowed handle: the C ABI writes the pointer
        /// through an out parameter, so the raw wrapper hands back the raw
        /// pointer and the public layer wraps it.
        handle: Produced,
    };

    pub const Input = struct {
        name: []u8,
        /// Null for a slice or handle input, whose spelling is not one word.
        scalar: ?[]const u8 = null,
        element: ?types.Element = null,
        handle: ?Handle = null,
        is_bool: bool = false,
        /// The shim supplies this argument -- an `std.mem.Allocator` or an
        /// `std.Io` the binding injected -- so it never crosses the C ABI and
        /// has no public spelling.
        ///
        /// Kept in the list rather than filtered out of it: `writeArgument`
        /// indexes by *semantic* parameter index, so removing an entry would
        /// shift every later one. It was not kept before, and an injected
        /// allocator therefore reached the signature as a `()` argument the
        /// caller had to supply.
        injected: bool = false,

        pub const Handle = struct {
            type_name: []const u8,
            c_name: []const u8,
            /// The C pointer is const, which for a parameter *is* recorded:
            /// `sumCopies(bias, left: Context, right: Context)` gives both
            /// handles `const zg_context *`. So a parameter gets the
            /// `&T`/`&mut T` distinction the receiver cannot have.
            is_const: bool,
        };

        /// The type the raw wrapper takes. A handle arrives as the bare
        /// pointer, not as the public wrapper: the raw module is below the
        /// wrapper and must not depend on it.
        pub fn writeRawType(self: Input, writer: *std.Io.Writer) !void {
            if (self.handle) |handle| return writer.print("*{s} {s}", .{
                if (handle.is_const) "const" else "mut",
                handle.c_name,
            });
            try self.writePublicType(writer);
        }

        /// The type the public signature takes. The two differ only for a
        /// handle, which the public API presents as a borrow of its wrapper.
        pub fn writePublicType(self: Input, writer: *std.Io.Writer) !void {
            if (self.handle) |handle| return writer.print("&{s}{s}", .{
                if (handle.is_const) "" else "mut ",
                handle.type_name,
            });
            if (self.element) |element| {
                if (element.text) return writer.writeAll("&str");
                return writer.print("&[{s}]", .{element.raw});
            }
            try writer.writeAll(self.scalar.?);
        }

        /// The expression the public layer passes to the raw wrapper.
        pub fn writeArgument(self: Input, writer: *std.Io.Writer) !void {
            if (self.handle != null) return writer.print("{s}.handle", .{self.name});
            try writer.writeAll(self.name);
        }
    };

    pub fn of(allocator: std.mem.Allocator, program: abi.Program, function: abi.AbiFn) !Shape {
        const origin = function.origin.*;
        const public_name = try rust.target.exportedFunctionNameAlloc(allocator, origin.name);
        errdefer allocator.free(public_name);
        const raw_name = try rawNameAlloc(allocator, origin);
        errdefer allocator.free(raw_name);
        const zig_names = try allocator.alloc([]const u8, origin.params.len);
        defer allocator.free(zig_names);
        for (origin.params, zig_names) |parameter, *name| name.* = parameter.name;
        // The names are moved into `inputs` below, so only the outer slice is
        // released here; `Shape.deinit` owns the strings.
        const names = try rust.paramNamesAlloc(allocator, zig_names);
        defer allocator.free(names);
        errdefer for (names) |name| allocator.free(name);
        var inputs: std.ArrayList(Input) = .empty;
        errdefer inputs.deinit(allocator);
        for (origin.params, names, 0..) |parameter, name, index| {
            var input: Input = .{ .name = name };
            if (parameter.injected != null) {
                input.injected = true;
                try inputs.append(allocator, input);
                continue;
            }
            switch (parameter.type) {
                .slice => {
                    input.element = types.sliceElement(parameter.type, function.paramString(index).role) orelse
                        return error.UnsupportedType;
                },
                .opaque_ptr => |pointer| {
                    const record = types.handleFor(program, pointer.ref) orelse return error.UnsupportedType;
                    input.handle = .{
                        .type_name = record.name,
                        .c_name = record.c_name,
                        .is_const = pointer.@"const",
                    };
                },
                .bool => {
                    input.scalar = "bool";
                    input.is_bool = true;
                },
                else => input.scalar = types.publicScalar(
                    parameter.type,
                    type_spelling.semanticScalar(program, parameter.type),
                ) orelse return error.UnsupportedType,
            }
            try inputs.append(allocator, input);
        }
        const has_status_code = origin.@"return" == .error_union;
        const payload_node: semantic.TypeNode = if (has_status_code) origin.@"return".error_union.payload.* else origin.@"return";
        var shape: Shape = .{
            .raw_name = raw_name,
            .public_name = public_name,
            .receiver = receiverOf(program, function),
            .inputs = try inputs.toOwnedSlice(allocator),
            .has_status_code = has_status_code,
            .declares_errors = function.errors.len != 0,
        };
        if (payload_node == .opaque_ptr) {
            const handle = types.renderableHandle(program, payload_node.opaque_ptr.ref) orelse
                return error.UnsupportedType;
            shape.payload = .{ .handle = .{
                .type_name = handle.record.name,
                .c_name = handle.record.c_name,
                .kind = handle.kind,
            } };
        } else if (payload_node == .slice) {
            const element = types.sliceElement(payload_node, function.ret_string) orelse
                return error.UnsupportedType;
            // Which of the two it is comes off the lowered ownership, not off
            // the type: `[]const T` is the same node whether the library keeps
            // the memory or hands it over.
            shape.payload = if (function.ownership.asBuffer()) |buffer|
                .{ .buffer = .{ .element = element, .release_symbol = releaseSymbol(program, buffer) } }
            else
                .{ .slice = element };
        } else if (payload_node != .void) {
            const spelling = try scalarSpelling(program, payload_node);
            // Whether the value comes back through an out parameter or as the
            // C return is the status channel's question, not the error set's.
            if (has_status_code) shape.payload = .{ .scalar = spelling } else shape.direct = spelling;
        }
        return shape;
    }

    /// Both spellings of one scalar. The two differ only for `bool`, which
    /// the C ABI carries as a byte, so this is the one place that difference
    /// is decided.
    fn scalarSpelling(program: abi.Program, node: semantic.TypeNode) !Direct {
        const scalar = type_spelling.semanticScalar(program, node);
        return .{
            .raw = types.rawScalar(scalar) orelse return error.UnsupportedType,
            .public = types.publicScalar(node, scalar) orelse return error.UnsupportedType,
            .is_bool = node == .bool,
        };
    }

    /// The `extern` symbol the release half of a caller-owned buffer is
    /// exported under.
    fn releaseSymbol(program: abi.Program, buffer: abi.Ownership.Buffer) []const u8 {
        // By index, not by comparing `release_function`. That pointer reaches
        // into the table *before* checked promotion, while `AbiFn.origin`
        // reaches into the promoted one, so the two are never equal and the
        // comparison matched nothing at all. The index is documented as being
        // into the full, unfiltered `Program.functions`, which is the only
        // kind this backend sees: a document with sub-packages -- the one
        // thing that produces a filtered program -- is refused.
        return program.functions[buffer.release].symbol;
    }

    /// Whether this call takes a native handle pointer, and therefore has a
    /// safety precondition the raw layer cannot check: the pointer must be a
    /// live handle of the right type. `clippy` insists on exactly this --
    /// `not_unsafe_ptr_arg_deref` -- and it is right, so the wrapper is
    /// `unsafe fn` and the public wrapper discharges the precondition by
    /// owning the handle.
    pub fn touchesHandlePointer(self: Shape) bool {
        if (self.receiver != null) return true;
        for (self.inputs) |input| if (input.handle != null) return true;
        return false;
    }

    /// The receiver's record, read off the ABI parameter lowering created for
    /// it rather than off the semantic receiver name, so the constness is the
    /// one the C signature actually has.
    fn receiverOf(program: abi.Program, function: abi.AbiFn) ?Receiver {
        const name = function.origin.receiver orelse return null;
        const record = types.handleFor(program, name) orelse return null;
        for (function.params) |parameter| {
            if (parameter.role != .receiver) continue;
            return .{
                .type_name = record.name,
                .c_name = record.c_name,
                .is_const = parameter.scalar == .pointer and parameter.scalar.pointer.is_const,
            };
        }
        return null;
    }

    /// The raw module's name for one function: the owning type's snake
    /// spelling joined to the function's, or the function's alone when it has
    /// no owner. An owner is a dotted path once a binding names a nested
    /// namespace, and each segment converts on its own -- the same rule
    /// `naming.functionSymbolAlloc` uses for the C symbol.
    fn rawNameAlloc(allocator: std.mem.Allocator, origin: semantic.SemanticFn) ![]u8 {
        const name = try rust.target.exportedFunctionNameAlloc(allocator, origin.name);
        const owner = origin.receiver orelse origin.namespace orelse return name;
        defer allocator.free(name);
        var out: std.ArrayList(u8) = .empty;
        errdefer out.deinit(allocator);
        var segments = std.mem.splitScalar(u8, owner, '.');
        while (segments.next()) |segment| {
            const converted = try rust.target.exportedFunctionNameAlloc(allocator, segment);
            defer allocator.free(converted);
            try out.appendSlice(allocator, converted);
            try out.append(allocator, '_');
        }
        try out.appendSlice(allocator, name);
        return out.toOwnedSlice(allocator);
    }

    pub fn deinit(self: Shape, allocator: std.mem.Allocator) void {
        allocator.free(self.raw_name);
        allocator.free(self.public_name);
        for (self.inputs) |input| allocator.free(input.name);
        allocator.free(self.inputs);
    }

    /// The raw wrapper's return type. The raw layer reports the ABI as it is,
    /// so it always carries the status code when one exists; deciding what the
    /// code *means* is the public layer's job.
    pub fn writeRawResultType(self: Shape, writer: *std.Io.Writer) !void {
        if (self.payload) |payload| {
            try writer.writeAll(" -> (");
            switch (payload) {
                .scalar => |scalar| try writer.writeAll(scalar.raw),
                .slice => |element| try writer.print("*const {s}, usize", .{element.raw}),
                .buffer => |buffer| try writer.print("*const {s}, usize", .{buffer.element.raw}),
                .handle => |record| try writer.print("*mut {s}", .{record.c_name}),
            }
            if (self.has_status_code) try writer.writeAll(", i32");
            return writer.writeByte(')');
        }
        if (self.has_status_code) return writer.writeAll(" -> i32");
        if (self.direct) |direct| return writer.print(" -> {s}", .{direct.raw});
    }

    pub fn writeRawReturn(self: Shape, writer: *std.Io.Writer) !void {
        if (self.payload) |payload| {
            try writer.writeAll("    (");
            switch (payload) {
                .scalar, .handle => try writer.writeAll("out_result"),
                .slice, .buffer => try writer.writeAll("out_result_ptr, out_result_len"),
            }
            if (self.has_status_code) try writer.writeAll(", code");
            return writer.writeAll(")\n");
        }
    }
};
