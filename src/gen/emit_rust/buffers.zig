//! Caller-owned native buffers, owned rather than copied.
//!
//! Go's binding has to copy: its GC cannot own a Zig pointer, so the generated
//! body copies the payload into a Go slice and calls the release symbol before
//! returning, which is one allocation and one full copy per call. Rust can own
//! the allocation directly, so `OwnedSlice<T>` holds the pointer, the length
//! and the release function, derefs to `[T]`, and releases in `Drop`. Nothing
//! is copied on the way out.
//!
//! One generic type per crate rather than one per release function. A release
//! function shared by three returns would otherwise need a type name none of
//! the three own, and naming it after the release function reads no better;
//! carrying the release as a function pointer removes the question.
const std = @import("std");
const abi = @import("abi");
const emit = @import("../emit/emit.zig");

/// The Rust type name. A literal rather than a target rule: it names a type
/// this emitter invents, not one the binding declared.
pub const type_name = "OwnedSlice";

/// Whether any bound function hands a buffer over.
pub fn hasBuffers(program: abi.Program) bool {
    for (program.functions) |function| {
        if (function.ownership == .buffer) return true;
    }
    return false;
}

/// Whether `function` is the release half of some caller-owned buffer.
///
/// Such a function is deliberately *not* published. `OwnedSlice`'s `Drop`
/// owns the release, so a public `free_digits` beside it would be a
/// double-free waiting to be written -- and unlike Go, which publishes both
/// and documents the hazard, Rust can simply not offer the second one.
pub fn isRelease(program: abi.Program, function: abi.AbiFn) bool {
    for (program.functions) |candidate| {
        const buffer = candidate.ownership.asBuffer() orelse continue;
        // By index rather than by comparing `release_function` to
        // `AbiFn.origin`: the first points into the table before checked
        // promotion and the second into the promoted one, so the pointers are
        // never equal. See `raw.Shape.releaseSymbol`.
        if (buffer.release >= program.functions.len) continue;
        if (std.mem.eql(u8, program.functions[buffer.release].symbol, function.symbol)) return true;
    }
    return false;
}

pub fn renderBuffers(_: std.mem.Allocator, writer: *std.Io.Writer, _: abi.Program, _: emit.Options) !void {
    try writer.writeAll(
        \\// Code generated by zigo. DO NOT EDIT.
        \\
        \\//! Native buffers this binding hands over.
        \\
        \\/// A slice the native library allocated and handed to the caller.
        \\///
        \\/// Nothing is copied. The bytes this derefs to are the native
        \\/// allocation, and they are released when this value is dropped. The Go
        \\/// binding for the same function has to copy the payload and release it
        \\/// before returning, because Go's collector cannot own a Zig pointer;
        \\/// owning it here costs one allocation and one copy fewer per call.
        \\///
        \\/// Neither `Send` nor `Sync`: whether the bound library's allocator may
        \\/// be used from another thread is a fact about that library which zigo
        \\/// does not record.
        \\pub struct OwnedSlice<T> {
        \\    ptr: *const T,
        \\    len: usize,
        \\    release: unsafe extern "C" fn(*const T, usize),
        \\}
        \\
        \\impl<T> OwnedSlice<T> {
        \\    /// Takes ownership of a native allocation.
        \\    ///
        \\    /// # Safety
        \\    ///
        \\    /// `ptr` and `len` must describe an allocation `release` can free,
        \\    /// and no other value may own it. The generated wrapper that calls
        \\    /// this is the only caller.
        \\    pub(crate) unsafe fn from_raw(
        \\        ptr: *const T,
        \\        len: usize,
        \\        release: unsafe extern "C" fn(*const T, usize),
        \\    ) -> Self {
        \\        Self { ptr, len, release }
        \\    }
        \\
        \\    /// The bytes as a slice. Empty when the library handed over nothing.
        \\    #[must_use]
        \\    pub fn as_slice(&self) -> &[T] {
        \\        if self.ptr.is_null() || self.len == 0 {
        \\            return &[];
        \\        }
        \\        // The allocation is this value's for its whole lifetime, and the
        \\        // borrow returned here cannot outlive it.
        \\        unsafe { core::slice::from_raw_parts(self.ptr, self.len) }
        \\    }
        \\}
        \\
        \\impl OwnedSlice<u8> {
        \\    /// The bytes as text, replacing any invalid UTF-8.
        \\    ///
        \\    /// Borrows for valid input and allocates only for invalid input,
        \\    /// which is why a text buffer is an `OwnedSlice<u8>` like any other
        \\    /// rather than being copied into a `String` on the way out.
        \\    #[must_use]
        \\    pub fn to_str_lossy(&self) -> std::borrow::Cow<'_, str> {
        \\        String::from_utf8_lossy(self.as_slice())
        \\    }
        \\}
        \\
        \\impl<T> core::ops::Deref for OwnedSlice<T> {
        \\    type Target = [T];
        \\
        \\    fn deref(&self) -> &[T] {
        \\        self.as_slice()
        \\    }
        \\}
        \\
        \\impl<T: core::fmt::Debug> core::fmt::Debug for OwnedSlice<T> {
        \\    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        \\        self.as_slice().fmt(f)
        \\    }
        \\}
        \\
        \\impl<T> Drop for OwnedSlice<T> {
        \\    fn drop(&mut self) {
        \\        if self.ptr.is_null() {
        \\            return;
        \\        }
        \\        // The allocation is this value's, so releasing it here is the
        \\        // last use of the pointer.
        \\        unsafe { (self.release)(self.ptr, self.len) };
        \\    }
        \\}
        \\
    );
}
