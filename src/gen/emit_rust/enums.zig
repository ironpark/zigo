//! Named enum values above the integer C ABI. Integer-to-enum conversion is
//! always checked; an open Zig enum is an integer newtype, never a Rust enum
//! with an invalid discriminant. No Rust enum value crosses the extern block.
const std = @import("std");
const abi = @import("abi");
const semantic = @import("semantic");
const rust = @import("targets").rust;
const emit = @import("../emit/emit.zig");
const types = @import("types.zig");
const public = @import("public.zig");
const diagnostic = @import("diagnostic");

pub fn enabled(_: std.mem.Allocator, program: abi.Program, _: emit.Options) !bool {
    return program.enums.len != 0;
}

pub fn path(allocator: std.mem.Allocator, _: abi.Program, _: emit.Options) ![]u8 {
    return allocator.dupe(u8, "src/enum.rs");
}

/// Qualified because the same spelling appears in lib.rs and handle.rs.
pub fn typeNameAlloc(allocator: std.mem.Allocator, name: []const u8) ![]u8 {
    const converted = try rust.typeNameAlloc(allocator, name);
    defer allocator.free(converted);
    return std.fmt.allocPrint(allocator, "crate::{s}", .{converted});
}

fn isOpen(declaration: semantic.TypeDecl) bool {
    return !declaration.exhaustive or (declaration.open orelse false);
}

/// Declarations are checked even if no function mentions them: the enum file
/// exports every registered enum, so an unused invalid type must not slip past.
pub fn unsupportedIssues(allocator: std.mem.Allocator, program: abi.Program, issues: *std.ArrayList(diagnostic.Diagnostic)) !void {
    for (program.enums, 0..) |record, index| {
        const declaration = semantic.typeDecl(program.types, record.name).?;
        const name = try rust.typeNameAlloc(allocator, record.name);
        defer allocator.free(name);
        var reason: ?[]const u8 = null;
        if (types.rawScalar(record.tag) == null) reason = "the enum tag has no supported Rust integer representation";
        if (!isOpen(declaration) and program.liveFields(record.name).len == 0)
            reason = "a closed enum with no public members cannot have a Rust integer repr";
        if (!rust.words.isIdentifier(name)) reason = "the enum name is not a Rust type identifier";
        for ([_][]const u8{ "Result", "String", "Vec" }) |reserved| {
            if (std.mem.eql(u8, name, reserved)) reason = "the enum name would shadow a Rust prelude type used by the generated API";
        }
        // Names re-exported beside the enum types in the crate root.
        if ((public.hasErrors(program) and (std.mem.eql(u8, name, "Error") or std.mem.eql(u8, name, "ErrorKind"))) or
            (@import("buffers.zig").hasBuffers(program) and std.mem.eql(u8, name, "OwnedSlice")))
            reason = "the enum name collides with a generated Rust support type";
        for (program.handles) |handle| {
            if (types.renderableHandle(program, handle.name) != null and std.mem.eql(u8, name, handle.name))
                reason = "the enum name collides with a Rust handle type";
        }
        for (program.enums[0..index]) |previous| {
            const other = try rust.typeNameAlloc(allocator, previous.name);
            defer allocator.free(other);
            if (std.mem.eql(u8, name, other)) reason = "enum names collide after Rust PascalCase conversion";
        }
        const fields = program.liveFields(record.name);
        for (fields, 0..) |field, field_index| {
            const member = try rust.typeNameAlloc(allocator, field.name);
            defer allocator.free(member);
            if (!rust.words.isIdentifier(member)) reason = "an enum member is not a Rust variant identifier after PascalCase conversion";
            for (fields[0..field_index]) |previous| {
                const other = try rust.typeNameAlloc(allocator, previous.name);
                defer allocator.free(other);
                if (std.mem.eql(u8, member, other)) reason = "enum members collide after Rust PascalCase conversion";
            }
        }
        if (reason) |message| try issues.append(allocator, .{
            .severity = .@"error",
            .code = "ZIGO060",
            .message = try std.fmt.allocPrint(allocator, "the Rust target cannot bind enum `{s}`: {s}", .{ record.name, message }),
            .site = .{ .path = "semantic.json", .declaration = record.name },
            .hint = "rename the conflicting declaration or use a supported enum tag and public member set",
        });
    }
}

pub fn render(allocator: std.mem.Allocator, writer: *std.Io.Writer, program: abi.Program, _: emit.Options) !void {
    try writer.writeAll("// Code generated by zigo. DO NOT EDIT.\n\n//! Named Zig enum values. The native ABI carries only their integer tags.\n//! Convert to a tag with `Into`, and from a tag with `TryFrom`.\n//! Closed enums reject unknown and omitted members. Open enums preserve all\n//! values within the original Zig tag range, including unnamed values.\n//! A native result outside the public type's domain panics after status checks.\n");
    for (program.enums) |record| {
        const declaration = semantic.typeDecl(program.types, record.name).?;
        const name = try rust.typeNameAlloc(allocator, record.name);
        defer allocator.free(name);
        const tag = types.rawScalar(record.tag).?;
        const fields = program.liveFields(record.name);
        const open = isOpen(declaration);
        try writer.writeByte('\n');
        if (declaration.doc) |doc| try public.writeDocComment(writer, doc, "///");
        try writer.writeAll("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n");
        if (open) {
            try writer.print("#[repr(transparent)]\npub struct {s}({s});\n", .{ name, tag });
            if (fields.len != 0) try writer.print("\n// Keep the same Type::Member spelling as closed enums.\n#[allow(non_upper_case_globals)]\nimpl {s} {{\n", .{name});
        } else {
            try writer.print("#[repr({s})]\npub enum {s} {{\n", .{ tag, name });
        }
        for (fields) |field| {
            const member = try rust.typeNameAlloc(allocator, field.name);
            defer allocator.free(member);
            if (open)
                try writer.print("    pub const {s}: Self = Self({d});\n", .{ member, field.value.? })
            else
                try writer.print("    {s} = {d},\n", .{ member, field.value.? });
        }
        if (!open or fields.len != 0) try writer.writeAll("}\n");
        try writer.print("\nimpl ::core::convert::From<{s}> for {s} {{\n    fn from(value: {s}) -> Self {{\n        {s}\n    }}\n}}\n", .{ name, tag, name, if (open) "value.0" else "value as Self" });
        try writer.print("\nimpl ::core::convert::TryFrom<{s}> for {s} {{\n    type Error = {s};\n\n    fn try_from(value: {s}) -> ::core::result::Result<Self, {s}> {{\n", .{ tag, name, tag, tag, tag });
        if (open) {
            const integer = declaration.tag_type.?.int;
            if (!integer.is_usize and integer.bits < abi.promotedIntBits(integer.bits)) {
                const shift: u7 = @intCast(integer.bits - @intFromBool(integer.signed));
                const bound = @as(i128, 1) << shift;
                const min: i128 = if (integer.signed) -bound else 0;
                try writer.print("        if !({d}..={d}).contains(&value) {{\n            return ::core::result::Result::Err(value);\n        }}\n", .{ min, bound - 1 });
            }
            try writer.writeAll("        ::core::result::Result::Ok(Self(value))\n");
        } else {
            try writer.writeAll("        match value {\n");
            for (fields) |field| {
                const member = try rust.typeNameAlloc(allocator, field.name);
                defer allocator.free(member);
                try writer.print("            {d} => ::core::result::Result::Ok(Self::{s}),\n", .{ field.value.?, member });
            }
            if (!coversTag(record.tag, fields.len)) try writer.writeAll("            _ => ::core::result::Result::Err(value),\n");
            try writer.writeAll("        }\n");
        }
        try writer.writeAll("    }\n}\n");
        if (declaration.text orelse false) try renderText(allocator, writer, fields, name, open, coversTag(record.tag, fields.len));
    }
}

fn renderText(allocator: std.mem.Allocator, writer: *std.Io.Writer, fields: []const semantic.TypeField, name: []const u8, open: bool, complete: bool) !void {
    // An open enum may expose no names at all. Neither trait needs a match.
    if (fields.len == 0) return writer.print(
        \\
        \\impl ::core::fmt::Display for {0s} {{
        \\    fn fmt(&self, f: &mut ::core::fmt::Formatter<'_>) -> ::core::fmt::Result {{
        \\        write!(f, "{0s}({{}})", self.0)
        \\    }}
        \\}}
        \\
        \\/// No public member names are registered for this enum.
        \\impl ::core::str::FromStr for {0s} {{
        \\    type Err = &'static str;
        \\
        \\    fn from_str(_text: &str) -> ::core::result::Result<Self, &'static str> {{
        \\        ::core::result::Result::Err("invalid {0s} member name")
        \\    }}
        \\}}
        \\
    , .{name});
    try writer.print("\nimpl ::core::fmt::Display for {s} {{\n    fn fmt(&self, f: &mut ::core::fmt::Formatter<'_>) -> ::core::fmt::Result {{\n        match {s} {{\n", .{ name, if (open) "self.0" else "self" });
    for (fields) |field| {
        const member = try rust.typeNameAlloc(allocator, field.name);
        defer allocator.free(member);
        if (open)
            try writer.print("            {d} => f.write_str(\"{s}\"),\n", .{ field.value.?, field.name })
        else
            try writer.print("            Self::{s} => f.write_str(\"{s}\"),\n", .{ member, field.name });
    }
    if (open and !complete) try writer.print("            value => write!(f, \"{s}({{value}})\"),\n", .{name});
    try writer.print("        }}\n    }}\n}}\n\n/// Parses public Zig member names; numeric diagnostic spellings are not accepted.\nimpl ::core::str::FromStr for {s} {{\n    type Err = &'static str;\n\n    fn from_str(text: &str) -> ::core::result::Result<Self, &'static str> {{\n        match text {{\n", .{name});
    for (fields) |field| {
        const member = try rust.typeNameAlloc(allocator, field.name);
        defer allocator.free(member);
        try writer.print("            \"{s}\" => ::core::result::Result::Ok(Self::{s}),\n", .{ field.name, member });
    }
    try writer.print("            _ => ::core::result::Result::Err(\"invalid {s} member name\"),\n        }}\n    }}\n}}\n", .{name});
}

/// A full-width enum match needs no wildcard (which rustc would reject under
/// -D warnings). Validation already guarantees distinct member values.
fn coversTag(tag: abi.AbiScalar, count: usize) bool {
    const bits = switch (tag) {
        .signed_int, .unsigned_int => |bits| bits,
        else => return false,
    };
    return bits < 64 and @as(u128, count) == (@as(u128, 1) << @as(u7, @intCast(bits)));
}

test "unsupported enum declarations are diagnosed even without functions" {
    const cases = [_]struct { name: []const u8, fields: []const semantic.TypeField }{
        .{ .name = "Empty", .fields = &.{} },
        .{ .name = "Result", .fields = &.{.{ .name = "ok", .value = 0 }} },
        .{ .name = "Collision", .fields = &.{ .{ .name = "http_id", .value = 0 }, .{ .name = "httpId", .value = 1 } } },
        .{ .name = "Keyword", .fields = &.{.{ .name = "self", .value = 0 }} },
    };
    for (cases) |case| {
        var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
        defer arena.deinit();
        var issues: std.ArrayList(diagnostic.Diagnostic) = .empty;
        const program: abi.Program = .{
            .package = "sample",
            .prefix = "zg",
            .functions = &.{},
            .types = &.{.{ .name = case.name, .kind = .@"enum", .fields = case.fields, .tag_type = .{ .int = .{ .bits = 8, .signed = false } } }},
            .enums = &.{.{ .name = case.name, .c_name = "zg_enum", .tag = .{ .unsigned_int = 8 }, .constants = &.{} }},
        };
        try unsupportedIssues(arena.allocator(), program, &issues);
        try std.testing.expectEqual(@as(usize, 1), issues.items.len);
        try std.testing.expectEqualStrings("ZIGO060", issues.items[0].code);
        try std.testing.expectEqualStrings(case.name, issues.items[0].site.declaration);
    }
}

test "complete integer domains do not emit unreachable wildcard arms" {
    try std.testing.expect(coversTag(.{ .unsigned_int = 8 }, 256));
    try std.testing.expect(coversTag(.{ .signed_int = 8 }, 256));
    try std.testing.expect(!coversTag(.{ .unsigned_int = 8 }, 255));
    try std.testing.expect(!coversTag(.{ .unsigned_int = 64 }, 256));
}
