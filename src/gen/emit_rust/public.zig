//! The public Rust crate root: safe functions over the raw layer, with
//! `Result<T, Error>` where the Zig declaration returns an error union.
//!
//! This is where Rust is a better fit than Go rather than a worse one. Go's
//! fallible call returns `(T, error)` and the generated body has to decide
//! what `T` means when `error` is set; Rust's returns `Result<T, Error>`, so
//! the absent payload is not representable and there is nothing to decide.
const std = @import("std");
const abi = @import("abi");
const semantic = @import("semantic");
const emit = @import("../emit/emit.zig");
// The Rust target's own rules, reached the way the Go emitter reaches Go's:
// through the `targets` module, since `targets.zig` owns those files.
const rust = @import("targets").rust;
const handles = @import("handles.zig");
const raw = @import("raw.zig");
const types = @import("types.zig");

/// Whether the crate has an error module at all. A binding whose functions
/// are all infallible has no codes to name, so `lib.rs` must not declare the
/// module -- Rust would fail to find the file the generator did not write.
pub fn hasErrors(program: abi.Program) bool {
    return program.error_codes.len != 0;
}

pub fn renderLib(allocator: std.mem.Allocator, writer: *std.Io.Writer, program: abi.Program, options: emit.Options) !void {
    try writer.writeAll("// Code generated by zigo. DO NOT EDIT.\n\n");
    if (program.doc) |doc| {
        try writeDocComment(writer, doc, "//!");
    } else {
        try writer.print("//! Rust bindings for `{s}`, generated by zigo.\n", .{program.package});
    }
    try writer.writeAll("\npub mod raw;\n");
    if (hasErrors(program)) try writer.writeAll("\nmod error;\npub use error::{Error, ErrorKind};\n");
    if (handles.hasHandles(program)) try writer.writeAll("\nmod handle;\npub use handle::*;\n");
    // Filtered by *placement*, not by support: the refusal for a shape this
    // backend cannot render happens once, upstream, over the whole document.
    // A constructor and a method belong to a handle's `impl` block and a
    // destructor belongs to its `Drop`, so this file writes the free
    // functions and `handle.rs` writes the rest. `types.placementOf` is the
    // one definition of that split, so no function can be emitted twice or
    // dropped by both emitters believing the other has it.
    for (program.functions) |function| {
        if (types.placementOf(program, function) != .free_function) continue;
        try renderFunction(allocator, writer, program, function, options);
    }
}

fn renderFunction(
    allocator: std.mem.Allocator,
    writer: *std.Io.Writer,
    program: abi.Program,
    function: abi.AbiFn,
    _: emit.Options,
) !void {
    const shape = try raw.Shape.of(allocator, program, function);
    defer shape.deinit(allocator);
    try writer.writeByte('\n');
    var documented = false;
    if (function.origin.doc) |doc| {
        try writeDocComment(writer, doc, "///");
        documented = true;
    }
    if (function.errors.len != 0) {
        if (documented) try writer.writeAll("///\n");
        try writer.writeAll("/// # Errors\n///\n");
        for (function.errors) |code| try writer.print("/// - [`ErrorKind::{s}`]\n", .{code.name});
    }
    try writer.print("pub fn {s}(", .{shape.raw_name});
    try writeParameters(writer, shape, null);
    try writer.writeByte(')');
    try writePublicResultType(writer, shape);
    try writer.writeAll(" {\n");
    try writeBody(allocator, writer, shape, function, null);
    try writer.writeAll("}\n");
}

/// The public signature's result.
///
/// `Result<T, Error>` only when the binding declares a Zig error set. A call
/// that merely has a status channel -- which is every call with a handle or a
/// narrow-integer parameter, since `lower.promoteCheckedFunctions` gives those
/// an empty error union so a native panic has somewhere to go -- returns its
/// payload, because the codes it can report are defects rather than
/// conditions. See `raw.Shape.declares_errors`.
pub fn writePublicResultType(writer: *std.Io.Writer, shape: raw.Shape) !void {
    if (shape.declares_errors) {
        try writer.writeAll(" -> Result<");
        try writePayloadType(writer, shape);
        return writer.writeAll(", Error>");
    }
    if (shape.payload == null and shape.direct == null) return;
    try writer.writeAll(" -> ");
    try writePayloadType(writer, shape);
}

fn writePayloadType(writer: *std.Io.Writer, shape: raw.Shape) !void {
    if (shape.payload) |payload| switch (payload) {
        .scalar => |scalar| return writer.writeAll(scalar.public),
        .handle => |handle| return handle.writePublicType(writer),
        // An owned copy, not a borrow. The native buffer's lifetime is the
        // library's, and a borrowed slice would need a lifetime the public
        // signature has nothing to tie it to; copying is what the minimal
        // backend can promise. A `Drop` wrapper over the native buffer is the
        // obvious next step and is not in this scope.
        .slice => |element| return if (element.text)
            writer.writeAll("String")
        else
            writer.print("Vec<{s}>", .{element.raw}),
    };
    if (shape.direct) |direct| return writer.writeAll(direct.public);
    try writer.writeAll("()");
}

/// One public function's body, shared by the free functions in `lib.rs` and
/// the `impl` blocks in `handle.rs`.
///
/// `self_expression` is what the raw wrapper's receiver parameter is passed,
/// or null for a free function. Sharing the writer rather than giving methods
/// their own is what keeps the status-code rule, the slice copy and the `Ok`
/// wrapping from drifting apart between the two.
pub fn writeBody(
    allocator: std.mem.Allocator,
    writer: *std.Io.Writer,
    shape: raw.Shape,
    function: abi.AbiFn,
    self_expression: ?[]const u8,
) !void {
    // The raw wrapper's result is destructured to exactly what this function
    // has to look at, so an unused binding never reaches the compiler.
    if (shape.payload) |payload| {
        switch (payload) {
            .scalar, .handle => try writer.writeAll("    let (result"),
            .slice => try writer.writeAll("    let (result_ptr, result_len"),
        }
        if (shape.has_status_code) try writer.writeAll(", code");
        try writer.writeAll(") = ");
    } else if (shape.has_status_code) {
        try writer.writeAll("    let code = ");
    } else {
        // Nothing to inspect after the call, so it is the tail expression.
        // `bool` is the one result that still needs a word after it: the C ABI
        // carries a Zig `bool` as a byte.
        try writer.writeAll("    ");
        try writeCall(writer, shape, self_expression);
        if (shape.direct) |direct| if (direct.is_bool) try writer.writeAll(" != 0");
        return writer.writeByte('\n');
    }
    try writeCall(writer, shape, self_expression);
    try writer.writeAll(";\n");
    // What a non-zero code means is the whole of the status-channel decision,
    // spelled in two lines. A declared error set makes it a value the caller
    // handles; an empty one makes it a defect, and the only codes reachable
    // there are an invalid handle -- unreachable in Rust -- and a caught Zig
    // panic.
    if (shape.has_status_code) {
        if (shape.declares_errors) {
            try writer.print(
                "    if code != 0 {{\n        return Err(Error::from_code(\"{s}\", code));\n    }}\n",
                .{function.origin.name},
            );
        } else {
            try writer.print(
                "    if code != 0 {{\n        raw::panic_native(\"{s}\", code);\n    }}\n",
                .{function.origin.name},
            );
        }
    }
    if (shape.payload) |payload| {
        switch (payload) {
            .handle => |handle| {
                // A call that reported success must have written a handle.
                // Without this an owned wrapper would hand a null pointer to
                // the destructor in `Drop`, and a borrowed one would deref it.
                try writer.print(
                    "    assert!(\n        !result.is_null(),\n        \"zigo: {s}: the native call reported success without writing a handle\"\n    );\n    ",
                    .{function.origin.name},
                );
                return switch (handle.kind) {
                    .owned => writeResultExpression(writer, shape, "Self { handle: result }"),
                    // The lifetime is inferred from the receiver's borrow, so
                    // the constructor expression names only the marker.
                    .borrowed => writeResultExpression(writer, shape, try std.fmt.allocPrint(
                        allocator,
                        "{s} {{ handle: result, owner: core::marker::PhantomData }}",
                        .{handle.type_name},
                    )),
                };
            },
            .scalar => |scalar| {
                try writer.writeAll("    ");
                // A `bool` payload crossed as a byte, so the public value is
                // the comparison rather than the name.
                if (scalar.is_bool) return writeResultExpression(writer, shape, "result != 0");
            },
            // The pointer is the library's for the duration of the call only,
            // so the bytes are copied before returning. A null pointer with a
            // zero length is an empty result, which `from_raw_parts` may not
            // be handed.
            //
            // One binding, so one allocation and one copy. Converting inside
            // the `else` arm matters for text: `from_utf8_lossy` borrows for
            // valid UTF-8, so going through an owned `Vec` first would copy
            // the whole buffer a second time and drop the first.
            .slice => |element| {
                // An infallible slice result is the tail expression. Binding
                // it to a name only to return the name is what `clippy` calls
                // `let_and_return`; a fallible one is not, since its tail is
                // the `Ok` around the name.
                try writer.writeAll(if (shape.declares_errors) "    let result = " else "    ");
                try writer.print(
                    \\if result_ptr.is_null() || result_len == 0 {{
                    \\        {s}::new()
                    \\    }} else {{
                    \\        let bytes = unsafe {{ core::slice::from_raw_parts(result_ptr, result_len) }};
                    \\        {s}
                    \\    }}
                , .{
                    if (element.text) "String" else "Vec",
                    if (element.text) "String::from_utf8_lossy(bytes).into_owned()" else "bytes.to_vec()",
                });
                if (!shape.declares_errors) return writer.writeByte('\n');
                try writer.writeAll(";\n    ");
            },
        }
        return writeResultExpression(writer, shape, "result");
    }
    // A call whose payload is `void` and whose error set is declared: the
    // status code was the whole result, and it became an `Err` above.
    if (shape.declares_errors) try writer.writeAll("    Ok(())\n");
}

/// The call into the raw wrapper, receiver first when there is one.
///
/// A wrapper that takes a handle pointer is `unsafe fn`, and this is where its
/// precondition is discharged: every pointer passed here comes out of a
/// wrapper that owns a live native object for its whole lifetime, because the
/// only way to obtain one is a constructor and the only way to release one is
/// `Drop`.
fn writeCall(writer: *std.Io.Writer, shape: raw.Shape, self_expression: ?[]const u8) !void {
    const wrap = shape.touchesHandlePointer();
    if (wrap) try writer.writeAll("unsafe { ");
    try writer.print("raw::{s}(", .{shape.raw_name});
    if (self_expression) |expression| try writer.writeAll(expression);
    for (shape.inputs, 0..) |input, index| {
        if (index != 0 or self_expression != null) try writer.writeAll(", ");
        try input.writeArgument(writer);
    }
    try writer.writeByte(')');
    if (wrap) try writer.writeAll(" }");
}

/// One public function's parameter list, without the enclosing parentheses and
/// without the receiver, which an `impl` block spells as `&self`.
pub fn writeParameters(writer: *std.Io.Writer, shape: raw.Shape, leading: ?[]const u8) !void {
    if (leading) |value| try writer.writeAll(value);
    for (shape.inputs, 0..) |input, index| {
        if (index != 0 or leading != null) try writer.writeAll(", ");
        try writer.print("{s}: ", .{input.name});
        try input.writePublicType(writer);
    }
}

pub fn writeResultExpression(writer: *std.Io.Writer, shape: raw.Shape, expression: []const u8) !void {
    if (shape.declares_errors) return writer.print("Ok({s})\n", .{expression});
    try writer.print("{s}\n", .{expression});
}

/// The error module: one enum of the Zig error names this binding can report,
/// plus the two codes that are not Zig errors at all -- a caught native panic
/// and a code this build does not know.
pub fn renderErrors(allocator: std.mem.Allocator, writer: *std.Io.Writer, program: abi.Program, _: emit.Options) !void {
    try writer.writeAll(
        "// Code generated by zigo. DO NOT EDIT.\n\n" ++
            "//! The error a fallible binding reports.\n\n" ++
            "use crate::raw;\n\n" ++
            "/// Which error a failed call reported.\n" ++
            "///\n" ++
            "/// Non-exhaustive: a later version of the bound library can add a Zig\n" ++
            "/// error, and matching on it exhaustively today would then stop\n" ++
            "/// compiling for a change that is not breaking.\n" ++
            "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n" ++
            "#[non_exhaustive]\n" ++
            "pub enum ErrorKind {\n",
    );
    for (program.error_codes) |code| {
        if (code.code <= 0) continue;
        const name = try rust.typeNameAlloc(allocator, code.name);
        defer allocator.free(name);
        try writer.print("    /// Zig `error.{s}`, stable code {d}.\n    {s},\n", .{ code.name, code.code, name });
    }
    try writer.writeAll(
        "    /// A Zig panic caught at the native boundary. `Error::message`\n" ++
            "    /// carries the panic text when the shim recorded one.\n" ++
            "    NativePanic,\n" ++
            "    /// A status code this build of the binding has no name for, which\n" ++
            "    /// means the native library is newer than the generated crate.\n" ++
            "    Unknown,\n" ++
            "}\n\n" ++
            "/// A stable Zig error-set value returned by the generated binding.\n" ++
            "///\n" ++
            "/// `code` is the integer recorded in `errors.lock.json` and is stable\n" ++
            "/// across regenerations; `kind` is the name it had when this crate was\n" ++
            "/// generated. Compare on `kind` unless you are persisting the value.\n" ++
            "#[derive(Debug, Clone, PartialEq, Eq)]\n" ++
            "pub struct Error {\n" ++
            "    /// The stable integer stored in `errors.lock.json`.\n" ++
            "    pub code: i32,\n" ++
            "    /// Which error this is.\n" ++
            "    pub kind: ErrorKind,\n" ++
            "    /// The generated call that returned it.\n" ++
            "    pub operation: &'static str,\n" ++
            "    /// The native panic message, when `kind` is `ErrorKind::NativePanic`.\n" ++
            "    pub message: Option<String>,\n" ++
            "}\n\n" ++
            "impl Error {\n" ++
            "    /// Classifies one status code. A code at or below -256 is a caught\n" ++
            "    /// native panic, and the message travels with the code rather than\n" ++
            "    /// with the return value, so it is read here.\n" ++
            "    pub(crate) fn from_code(operation: &'static str, code: i32) -> Self {\n" ++
            "        if code <= -256 {\n" ++
            "            return Self {\n" ++
            "                code,\n" ++
            "                kind: ErrorKind::NativePanic,\n" ++
            "                operation,\n" ++
            "                message: Some(raw::panic_message(code)),\n" ++
            "            };\n" ++
            "        }\n" ++
            "        let kind = match code {\n",
    );
    for (program.error_codes) |code| {
        if (code.code <= 0) continue;
        const name = try rust.typeNameAlloc(allocator, code.name);
        defer allocator.free(name);
        try writer.print("            {d} => ErrorKind::{s},\n", .{ code.code, name });
    }
    try writer.writeAll(
        "            _ => ErrorKind::Unknown,\n" ++
            "        };\n" ++
            "        Self {\n" ++
            "            code,\n" ++
            "            kind,\n" ++
            "            operation,\n" ++
            "            message: None,\n" ++
            "        }\n" ++
            "    }\n" ++
            "\n" ++
            "    /// The Zig error name, as the bound library spells it.\n" ++
            "    pub fn name(&self) -> &'static str {\n" ++
            "        match self.kind {\n",
    );
    for (program.error_codes) |code| {
        if (code.code <= 0) continue;
        const name = try rust.typeNameAlloc(allocator, code.name);
        defer allocator.free(name);
        try writer.print("            ErrorKind::{s} => \"{s}\",\n", .{ name, code.name });
    }
    // No wildcard arm. `#[non_exhaustive]` binds other crates, not this one,
    // so a `_` here is an unreachable pattern rustc warns about -- and the
    // match is exhaustive by construction, since the arms above and the enum
    // are generated from the same table.
    try writer.writeAll(
        "            ErrorKind::NativePanic => \"NativePanic\",\n" ++
            "            ErrorKind::Unknown => \"Unknown\",\n" ++
            "        }\n" ++
            "    }\n" ++
            "}\n\n" ++
            "impl core::fmt::Display for Error {\n" ++
            "    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {\n" ++
            "        write!(f, \"zigo: {}: {}\", self.operation, self.name())?;\n" ++
            "        if let Some(message) = &self.message {\n" ++
            "            if !message.is_empty() {\n" ++
            "                write!(f, \": {message}\")?;\n" ++
            "            }\n" ++
            "        }\n" ++
            "        if self.kind == ErrorKind::Unknown {\n" ++
            "            write!(f, \"({})\", self.code)?;\n" ++
            "        }\n" ++
            "        Ok(())\n" ++
            "    }\n" ++
            "}\n\n" ++
            "impl std::error::Error for Error {}\n",
    );
}

/// A Zig doc comment as a Rust one. Zig doc text arrives as plain lines, and
/// `///` or `//!` is prefixed per line so a multi-line doc does not become one
/// unreadable run.
pub fn writeDocComment(writer: *std.Io.Writer, doc: []const u8, marker: []const u8) !void {
    var lines = std.mem.splitScalar(u8, std.mem.trimEnd(u8, doc, "\n"), '\n');
    while (lines.next()) |line| {
        const trimmed = std.mem.trimEnd(u8, line, " \t\r");
        if (trimmed.len == 0) try writer.print("{s}\n", .{marker}) else try writer.print("{s} {s}\n", .{ marker, trimmed });
    }
}
