const std = @import("std");
const abi = @import("abi");
const semantic = @import("semantic");
const naming = @import("naming.zig");

pub const Options = struct {
    go_module: []const u8,
    include_dir: []const u8 = "${SRCDIR}/../../../zig-out/include",
    library_dir: []const u8 = "${SRCDIR}/../../../zig-out/lib",
};

pub const Emitter = struct {
    pathAlloc: *const fn (std.mem.Allocator, abi.Program) anyerror![]u8,
    render: *const fn (std.mem.Allocator, *std.Io.Writer, abi.Program, Options) anyerror!void,
};

pub const all = [_]Emitter{
    .{ .pathAlloc = shimPath, .render = renderShim },
    .{ .pathAlloc = headerPath, .render = renderHeader },
    .{ .pathAlloc = rawPath, .render = renderRaw },
    .{ .pathAlloc = publicPath, .render = renderPublic },
};

fn shimPath(allocator: std.mem.Allocator, _: abi.Program) ![]u8 {
    return allocator.dupe(u8, "shim.zig");
}

fn headerPath(allocator: std.mem.Allocator, program: abi.Program) ![]u8 {
    const package = try naming.snakeAlloc(allocator, program.package);
    defer allocator.free(package);
    return std.fmt.allocPrint(allocator, "zigo_{s}.h", .{package});
}

fn rawPath(allocator: std.mem.Allocator, _: abi.Program) ![]u8 {
    return allocator.dupe(u8, "internal/raw/cgo.go");
}

fn publicPath(allocator: std.mem.Allocator, program: abi.Program) ![]u8 {
    const package = try naming.snakeAlloc(allocator, program.package);
    defer allocator.free(package);
    return std.fmt.allocPrint(allocator, "{s}/generated.go", .{package});
}

fn renderShim(allocator: std.mem.Allocator, writer: *std.Io.Writer, program: abi.Program, _: Options) !void {
    try writer.writeAll("// Code generated by zigo. DO NOT EDIT.\nconst target = @import(\"zigo_target\");\n\n");
    for (program.functions) |function| {
        try writer.print("export fn {s}(", .{function.symbol});
        for (function.params, 0..) |parameter, index| {
            if (index != 0) try writer.writeAll(", ");
            try writer.print("{s}: {s}", .{ parameter.name, zigType(parameter.scalar) });
        }
        try writer.print(") {s} {{\n    ", .{zigType(function.ret)});
        if (function.ret != .void) {
            if (function.ret == .bool_u8) try writer.writeAll("return @intFromBool(") else try writer.writeAll("return ");
        }
        const target_name = function.origin.name;
        try writer.print("target.{s}(", .{target_name});
        for (function.params, 0..) |parameter, index| {
            if (index != 0) try writer.writeAll(", ");
            if (parameter.scalar == .bool_u8) {
                try writer.print("{s} != 0", .{parameter.name});
            } else {
                try writer.writeAll(parameter.name);
            }
        }
        try writer.writeAll(")");
        if (function.ret == .bool_u8) try writer.writeByte(')');
        try writer.writeAll(";\n}\n");
    }
    _ = allocator;
}

fn renderHeader(allocator: std.mem.Allocator, writer: *std.Io.Writer, program: abi.Program, _: Options) !void {
    const package = try naming.snakeAlloc(allocator, program.package);
    defer allocator.free(package);
    try writer.print("// Code generated by zigo. DO NOT EDIT.\n#ifndef ZIGO_{s}_H\n#define ZIGO_{s}_H\n\n#include <stddef.h>\n#include <stdint.h>\n\n", .{ package, package });
    for (program.functions) |function| {
        try writer.print("{s} {s}(", .{ cType(function.ret), function.symbol });
        if (function.params.len == 0) try writer.writeAll("void");
        for (function.params, 0..) |parameter, index| {
            if (index != 0) try writer.writeAll(", ");
            try writer.print("{s} {s}", .{ cType(parameter.scalar), parameter.name });
        }
        try writer.writeAll(");\n");
    }
    try writer.print("\n#endif // ZIGO_{s}_H\n", .{package});
}

fn renderRaw(allocator: std.mem.Allocator, writer: *std.Io.Writer, program: abi.Program, options: Options) !void {
    const package = try naming.snakeAlloc(allocator, program.package);
    defer allocator.free(package);
    try writer.print("// Code generated by zigo. DO NOT EDIT.\npackage raw\n\n/*\n#cgo CFLAGS: -I{s}\n#cgo LDFLAGS: -L{s} -l{s}_zigo\n#include \"zigo_{s}.h\"\n*/\nimport \"C\"\n\n", .{ options.include_dir, options.library_dir, package, package });
    for (program.functions) |function| {
        const go_name = try naming.pascalAlloc(allocator, function.origin.name);
        defer allocator.free(go_name);
        try writer.print("func {s}(", .{go_name});
        for (function.params, 0..) |parameter, index| {
            if (index != 0) try writer.writeAll(", ");
            try writer.print("{s} {s}", .{ parameter.name, goType(parameter.scalar) });
        }
        try writer.writeByte(')');
        if (function.ret != .void) try writer.print(" {s}", .{goType(function.ret)});
        try writer.writeAll(" {\n\t");
        if (function.ret != .void) try writer.print("return {s}(", .{goType(function.ret)});
        try writer.print("C.{s}(", .{function.symbol});
        for (function.params, 0..) |parameter, index| {
            if (index != 0) try writer.writeAll(", ");
            try writer.print("C.{s}({s})", .{ cgoType(parameter.scalar), parameter.name });
        }
        try writer.writeByte(')');
        if (function.ret != .void) try writer.writeByte(')');
        try writer.writeAll("\n}\n");
    }
}

fn renderPublic(allocator: std.mem.Allocator, writer: *std.Io.Writer, program: abi.Program, options: Options) !void {
    const package = try naming.snakeAlloc(allocator, program.package);
    defer allocator.free(package);
    try writer.print("// Code generated by zigo. DO NOT EDIT.\npackage {s}\n\nimport \"{s}/internal/raw\"\n\n", .{ package, options.go_module });
    for (program.functions) |function| {
        const go_name = try naming.pascalAlloc(allocator, function.origin.name);
        defer allocator.free(go_name);
        try writer.print("func {s}(", .{go_name});
        for (function.origin.params, 0..) |parameter, index| {
            if (index != 0) try writer.writeAll(", ");
            try writer.print("{s} {s}", .{ parameter.name, publicGoType(parameter.type) });
        }
        try writer.writeByte(')');
        if (function.origin.@"return" != .void) try writer.print(" {s}", .{publicGoType(function.origin.@"return")});
        try writer.writeAll(" {\n\t");
        const returns_bool = function.origin.@"return" == .bool;
        if (function.origin.@"return" != .void) {
            if (returns_bool) try writer.writeAll("return raw.") else try writer.writeAll("return raw.");
        } else {
            try writer.writeAll("raw.");
        }
        try writer.print("{s}(", .{go_name});
        for (function.origin.params, 0..) |parameter, index| {
            if (index != 0) try writer.writeAll(", ");
            if (parameter.type == .bool) {
                try writer.print("boolToUint8({s})", .{parameter.name});
            } else {
                try writer.writeAll(parameter.name);
            }
        }
        try writer.writeByte(')');
        if (returns_bool) try writer.writeAll(" != 0");
        try writer.writeAll("\n}\n");
    }
    var needs_bool_helper = false;
    for (program.functions) |function| {
        for (function.origin.params) |parameter| {
            if (parameter.type == .bool) needs_bool_helper = true;
        }
    }
    if (needs_bool_helper) try writer.writeAll("func boolToUint8(value bool) uint8 {\n\tif value { return 1 }\n\treturn 0\n}\n");
}

fn zigType(value: abi.AbiScalar) []const u8 {
    return switch (value) {
        .void => "void",
        .bool_u8 => "u8",
        .signed_int => |bits| switch (bits) {
            8 => "i8",
            16 => "i16",
            32 => "i32",
            64 => "i64",
            else => unreachable,
        },
        .unsigned_int => |bits| switch (bits) {
            8 => "u8",
            16 => "u16",
            32 => "u32",
            64 => "u64",
            else => unreachable,
        },
        .float => |bits| switch (bits) {
            32 => "f32",
            64 => "f64",
            else => unreachable,
        },
        .pointer => unreachable,
    };
}

