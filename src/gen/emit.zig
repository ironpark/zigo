fn publicGoType(value: semantic.TypeNode) []const u8 {
    return switch (value) {
        .void => "",
        .bool => "bool",
        .int => |integer| if (integer.is_usize) (if (integer.signed) "int" else "uint") else switch (integer.bits) {
            8 => if (integer.signed) "int8" else "uint8",
            16 => if (integer.signed) "int16" else "uint16",
            32 => if (integer.signed) "int32" else "uint32",
            64 => if (integer.signed) "int64" else "uint64",
            else => unreachable,
        },
        .float => |float| switch (float.bits) {
            32 => "float32",
            64 => "float64",
            else => unreachable,
        },
        else => unreachable,
    };
}
