            try writer.print("\tcase {s}{s}:\n\t\treturn \"{s}\"\n", .{ declaration.name, field_name, field.name });
        }
        try writer.print("\tdefault:\n\t\treturn \"{s}(?)\"\n\t}}\n}}\n\n", .{declaration.name});
    }
}

