            if (auto_cleanup) try writer.writeAll("\tcleanup         runtime.Cleanup\n");
        } else {
            try writer.writeAll("\tptr  unsafe.Pointer\n\tonce sync.Once\n");
            if (auto_cleanup) try writer.writeAll("\tcleanup runtime.Cleanup\n");
