const std = @import("std");
const semantic = @import("semantic");
const plugin = @import("plugin");
const interfaces = @import("builtin_plugins").interfaces;
const hooks = @import("plugin_hooks.zig");
const public = @import("public.zig");
const emit = @import("emit.zig");

fn renderInterfacesBody(a: std.mem.Allocator, w: *std.Io.Writer, p: @import("abi").Program, o: emit.Options) !void {
    return interfaces.renderInterfacesBody(hooks.context(a, p, o), w);
}

test "an interface file lists the shared methods, Must variants, io.Closer and one assertion per type" {
    var int_batch: semantic.TypeNode = .{ .opaque_ptr = .{ .@"const" = false, .nullable = false, .ref = "IntBatch" } };
    var float_batch: semantic.TypeNode = .{ .opaque_ptr = .{ .@"const" = false, .nullable = false, .ref = "FloatBatch" } };
    const count: semantic.TypeNode = .{ .int = .{ .bits = 64, .is_usize = true, .signed = false } };
    const document: semantic.Semantic = .{
        .constructors = &.{
            .{ .deinit = "deinit", .init = "create", .type = "IntBatch" },
            .{ .deinit = "deinit", .init = "create", .type = "FloatBatch" },
        },
        .functions = &.{
            .{ .name = "create", .namespace = "IntBatch", .ownership = .caller, .params = &.{}, .@"return" = .{ .error_union = .{ .error_set = &.{}, .payload = &int_batch } }, .symbol = "zg_int_batch_create" },
            .{ .doc = "len reports how many values are staged.", .name = "len", .receiver = "IntBatch", .params = &.{}, .@"return" = count, .symbol = "zg_int_batch_len" },
            .{ .name = "deinit", .receiver = "IntBatch", .params = &.{}, .@"return" = .{ .void = {} }, .symbol = "zg_int_batch_deinit" },
            .{ .name = "create", .namespace = "FloatBatch", .ownership = .caller, .params = &.{}, .@"return" = .{ .error_union = .{ .error_set = &.{}, .payload = &float_batch } }, .symbol = "zg_float_batch_create" },
            .{ .name = "len", .receiver = "FloatBatch", .params = &.{}, .@"return" = count, .symbol = "zg_float_batch_len" },
            .{ .name = "deinit", .receiver = "FloatBatch", .params = &.{}, .@"return" = .{ .void = {} }, .symbol = "zg_float_batch_deinit" },
        },
        .interfaces = &.{.{ .doc = "Batch is any staged batch.", .methods = &.{"len"}, .name = "Batch", .types = &.{ "IntBatch", "FloatBatch" } }},
        .package = "batches",
        .prefix = "zg",
        .types = &.{
            .{ .kind = .@"opaque", .name = "IntBatch" },
            .{ .kind = .@"opaque", .name = "FloatBatch" },
        },
        .zig_version = "0.16.0",
    };
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    const lower = @import("lower");
    const program = try lower.semanticDocument(arena.allocator(), document, "batches", "zg", &.{});
    var facts: plugin.Facts = .{};
    var issues: std.ArrayList(@import("diagnostic").Diagnostic) = .empty;
    const options: emit.Options = .{ .go_module = "example.com/batches", .configurations = &.{.{ .name = "MUST", .json = "{\"enabled\":true}" }}, .facts = &facts };
    try hooks.analyze(arena.allocator(), program, options, &facts, &issues);
    try std.testing.expectEqual(@as(?interfaces.Mismatch, null), try interfaces.signatureMismatch(hooks.context(arena.allocator(), program, options)));

    var output: std.Io.Writer.Allocating = .init(std.testing.allocator);
    defer output.deinit();
    // Through the frame, which is how the generator renders a plugin file.
    try public.renderPublicFile(std.testing.allocator, &output.writer, program, options, renderInterfacesBody);
    try std.testing.expectEqualStrings(
        "// Code generated by zigo. DO NOT EDIT.\n\npackage batches\n\nimport \"io\"\n\n" ++
            "// Batch is any staged batch.\n// Batch is implemented by *IntBatch and *FloatBatch.\ntype Batch interface {\n" ++
            "\t// Len reports how many values are staged.\n\tLen() (uint, error)\n" ++
            "\t// MustLen calls Len and panics with its typed error on failure.\n\tMustLen() uint\n" ++
            "\tio.Closer\n}\n\nvar _ Batch = (*IntBatch)(nil)\nvar _ Batch = (*FloatBatch)(nil)\n",
        output.written(),
    );

    // A parameter type that differs between the two is the first mismatch.
    var wide: semantic.TypeNode = .{ .int = .{ .bits = 64, .signed = true } };
    _ = &wide;
    var narrow_document = document;
    var functions: [6]semantic.SemanticFn = undefined;
    for (document.functions, 0..) |function, index| functions[index] = function;
    functions[4].@"return" = .{ .int = .{ .bits = 32, .signed = true } };
    narrow_document.functions = &functions;
    const mismatched = try lower.semanticDocument(arena.allocator(), narrow_document, "batches", "zg", &.{});
    var other_facts: plugin.Facts = .{};
    var other_options = options;
    other_options.facts = &other_facts;
    try hooks.analyze(arena.allocator(), mismatched, other_options, &other_facts, &issues);
    const mismatch = (try interfaces.signatureMismatch(hooks.context(arena.allocator(), mismatched, other_options))) orelse return error.MissingMismatch;
    try std.testing.expectEqualStrings("len", mismatch.method);
    try std.testing.expectEqualStrings("Len() (uint, error) +Must", mismatch.first_signature);
    try std.testing.expectEqualStrings("Len() (int32, error) +Must", mismatch.second_signature);
    try std.testing.expectEqualStrings("FloatBatch", mismatch.second_type);
}

fn findMustVariantIssue(allocator: std.mem.Allocator, document: semantic.Semantic) !?@import("diagnostic").Diagnostic {
    const lower = @import("lower");
    const program = try lower.semanticDocument(allocator, document, document.package, document.prefix, &.{});
    var facts: plugin.Facts = .{};
    var issues: std.ArrayList(@import("diagnostic").Diagnostic) = .empty;
    const options: emit.Options = .{ .go_module = "example.com/test", .configurations = &.{.{ .name = "MUST", .json = "{\"enabled\":true}" }}, .facts = &facts };
    try hooks.analyze(allocator, program, options, &facts, &issues);
    return if (issues.items.len != 0) issues.items[0] else null;
}
test "generated Must names participate in ZIGO024 collision checks" {
    const document: semantic.Semantic = .{
        .functions = &.{
            .{
                .name = "ping",
                .params = &.{},
                .receiver = "Handle",
                .@"return" = .{ .void = {} },
                .symbol = "zg_handle_ping",
            },
            .{
                .name = "mustPing",
                .params = &.{},
                .receiver = "Handle",
                .@"return" = .{ .void = {} },
                .symbol = "zg_handle_must_ping",
            },
        },
        .package = "collision",
        .prefix = "zg",
        .types = &.{.{ .kind = .@"opaque", .name = "Handle" }},
        .zig_version = "0.16.0",
    };
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    const issue = (try findMustVariantIssue(arena.allocator(), document)) orelse return error.MissingDiagnostic;
    try std.testing.expectEqualStrings("ZIGO024", issue.code);
    try std.testing.expect(std.mem.indexOf(u8, issue.message, "MustPing") != null);
}

test "a callback signature flagged go_error elsewhere gives a free function a Must variant" {
    var status: semantic.TypeNode = .{ .int = .{ .bits = 32, .signed = true, .is_usize = false } };
    const observer: semantic.TypeNode = .{ .callback = .{ .has_userdata = true, .params = &.{}, .@"return" = &status } };
    const usize_node: semantic.TypeNode = .{ .int = .{ .bits = 64, .signed = false, .is_usize = true } };
    const document: semantic.Semantic = .{
        .functions = &.{
            .{
                .name = "run",
                .params = &.{
                    .{ .name = "observer", .type = observer },
                    .{ .name = "userdata", .type = usize_node },
                },
                .@"return" = .{ .void = {} },
                .symbol = "zg_run",
            },
            .{
                .name = "watch",
                .params = &.{
                    .{ .go_error = true, .name = "observer", .type = observer },
                    .{ .name = "userdata", .type = usize_node },
                },
                .@"return" = .{ .void = {} },
                .symbol = "zg_watch",
            },
            .{ .name = "mustRun", .params = &.{}, .@"return" = .{ .void = {} }, .symbol = "zg_must_run" },
        },
        .package = "collision",
        .prefix = "zg",
        .zig_version = "0.16.0",
    };
    var arena = std.heap.ArenaAllocator.init(std.testing.allocator);
    defer arena.deinit();
    const issue = (try findMustVariantIssue(arena.allocator(), document)) orelse return error.MissingDiagnostic;
    try std.testing.expectEqualStrings("ZIGO024", issue.code);
    try std.testing.expect(std.mem.indexOf(u8, issue.message, "MustRun") != null);
}
