//! The Zig shim: exported C entry points that call into the target module.
const type_spelling = @import("type_spelling.zig");
const target_types = @import("target_types.zig");
const std = @import("std");
const abi = @import("abi");
const semantic = @import("semantic");
const naming = @import("naming");
const common = @import("common.zig");
const emit = @import("emit.zig");
const header = @import("header.zig");
const materialized = @import("materialized.zig");
const materialized_encoder = @import("materialized_encoder.zig");
const raw = @import("raw.zig");

pub fn renderShim(allocator: std.mem.Allocator, writer: *std.Io.Writer, program: abi.Program, _: emit.Options) !void {
    // The panic bridge carries the binding's prefix like every other symbol
    // in the archive: two bindings linked into one binary each bring their
    // own, and an unprefixed pair would collide at link time.
    try writer.print(
        "// Code generated by zigo. DO NOT EDIT.\n" ++
            "const std = @import(\"std\");\n" ++
            "const target = @import(\"zigo_target\");\n\n" ++
            "extern fn {0s}_panic_bridge(message: [*]const u8, length: usize) callconv(.c) noreturn;\n" ++
            "fn panicHandler(message: []const u8, _: ?usize) noreturn {{\n" ++
            "    {0s}_panic_bridge(message.ptr, message.len);\n" ++
            "}}\n" ++
            "pub const panic = std.debug.FullPanic(panicHandler);\n\n",
        .{program.prefix},
    );
    // Set by whatever the prelude wrote after the panic bridge, so the blank
    // line that separates it from the exports is written once and only when
    // there is something to separate.
    var wrote_prelude = false;
    if (target_types.programNeedsTargetTypeResolver(program)) {
        try target_types.writeTargetTypeResolver(writer);
        wrote_prelude = true;
    }
    if (program.backend == .cgo) {
        for (program.functions) |function| {
            for (function.origin.params, 0..) |parameter, parameter_index| {
                if (parameter.type != .callback) continue;
                wrote_prelude = true;
                const name = try common.callbackTrampolineNameAlloc(allocator, function, parameter_index);
                defer allocator.free(name);
                try writer.print("extern fn {s}(", .{name});
                for (parameter.type.callback.params, 0..) |callback_parameter, index| {
                    if (index != 0) try writer.writeAll(", ");
                    try writer.print("p{d}: ", .{index});
                    try type_spelling.writeZigType(writer, program, type_spelling.semanticScalar(program, callback_parameter));
                }
                try writer.writeAll(") callconv(.c) ");
                try type_spelling.writeZigType(writer, program, type_spelling.semanticScalar(program, parameter.type.callback.@"return".*));
                try writer.writeAll(";\n");
                if (common.callbackHasPackedParam(program, parameter.type.callback)) {
                    const thunk = try common.callbackPackedThunkNameAlloc(allocator, function, parameter_index);
                    defer allocator.free(thunk);
                    try writeCallbackThunkSignature(writer, program, parameter.type.callback, thunk);
                    try writeCallbackThunkCall(writer, program, parameter.type.callback, name, false);
                }
            }
        }
    }
    if (program.backend == .cgo) {
        for ([_]semantic.StreamDirection{ .writer, .reader }) |direction| {
            if (!common.programHasStreamDirection(program, direction)) continue;
            const trampoline = try common.streamTrampolineNameAlloc(allocator, program, direction);
            defer allocator.free(trampoline);
            wrote_prelude = true;
            if (direction == .writer)
                try writer.print("extern fn {s}(ptr: [*]const u8, len: usize, userdata: usize) callconv(.c) i32;\n", .{trampoline})
            else
                try writer.print("extern fn {s}(ptr: [*]u8, cap: usize, userdata: usize) callconv(.c) i32;\n", .{trampoline});
        }
    }
    if (program.backend == .purego) {
        for (program.functions) |function| {
            for (function.origin.params, 0..) |_, parameter_index| {
                if (common.needsCallbackBitThunk(program, function, parameter_index)) wrote_prelude = true;
            }
        }
        try renderCallbackBitThunks(allocator, writer, program);
    }
    if (wrote_prelude) try writer.writeByte('\n');
    if (common.programHasStreams(program)) try writer.writeAll(stream_adapters);
    try materialized_encoder.renderMaterializedWalker(allocator, writer, program);
    try renderStreamAccessorHelpers(allocator, writer, program);
    for (program.functions) |function| {
        try writer.print("export fn {s}_impl(", .{function.symbol});
        for (function.params, 0..) |parameter, index| {
            if (index != 0) try writer.writeAll(", ");
            try writer.print("{s}: ", .{parameter.name});
            try type_spelling.writeZigType(writer, program, parameter.scalar);
        }
        try writer.writeAll(") ");
        try type_spelling.writeZigType(writer, program, function.ret);
        try writer.writeAll(" {\n");
        try writeCallbackBitBindings(allocator, writer, program, function);
        try writeShimStreamSetups(allocator, writer, program, function);
        try writeShimStringSliceSetups(allocator, writer, function);
        try writeNarrowIntegerGuards(writer, program, function);
        try writeNarrowSliceSetups(writer, program, function);
        if (function.materialized_out) |output| {
            const parameter = function.origin.params[output.source_index];
            try writer.print("    const zigo_{0s}_slice = {1s}.alloc(", .{ parameter.name, common.heapAllocator(program) });
            try target_types.writeTargetType(writer, program, output.root);
            try writer.print(", {0s}_len) " ++ materialized.materialize_oom ++ ";\n    defer {1s}.free(zigo_{0s}_slice);\n", .{ parameter.name, common.heapAllocator(program) });
        }
        try writer.writeAll("    ");

        if (function.origin.field_access) |field_access| {
            try writeFieldAccess(allocator, writer, program, function, field_access);
            continue;
        }

        if (function.origin.boxed == .create) {
            try writeBoxedConstructor(allocator, writer, program, function);
            continue;
        }

        if (function.materialized_return) |materialized_return| {
            try materialized.writeMaterializedReturn(allocator, writer, program, function, materialized_return);
            continue;
        }
        if (function.materialized_out) |output| {
            try materialized.writeMaterializedOutput(allocator, writer, program, function, output);
            continue;
        }

        if (function.origin.@"return" == .slice and !(function.ret_string == .c_string)) {
            try writer.writeAll("const result = ");
            try writeTargetCall(allocator, writer, program, function);
            try writer.writeAll(";\n");
            try writeShimSliceReturn(writer, program, function, "result");
            try writeSliceWrittenAssignments(writer, function);
            try writer.writeAll("}\n");
            continue;
        }

        // `?[]T`: a NULL `out_result_ptr` is the absent slice, which no length
        // can be mistaken for.
        if (semantic.isOptionalSlice(function.origin.@"return") and !(function.ret_string == .c_string)) {
            try writer.writeAll("const result = ");
            try writeTargetCall(allocator, writer, program, function);
            try writer.writeAll(" orelse {\n        out_result_ptr.* = null;\n        out_result_len.* = 0;\n");
            try writeSliceWrittenZeros(writer, function);
            try writer.writeAll("        return;\n    };\n    out_result_ptr.* = result.ptr;\n    out_result_len.* = result.len;\n");
            try writeSliceWrittenAssignments(writer, function);
            try writer.writeAll("}\n");
            continue;
        }

        // A plain `?T` return puts presence in the C return value and the
        // value in an out parameter, so an absent result leaves `out_result`
        // untouched and reports 0.
        if (function.origin.@"return" == .optional) {
            const child = function.origin.@"return".optional.child.*;
            try writer.writeAll("const result = ");
            try writeTargetCall(allocator, writer, program, function);
            try writer.writeAll(" orelse {\n");
            try writeSliceWrittenZeros(writer, function);
            try writer.writeAll("        return 0;\n    };\n    out_result.* = ");
            try writeZigReturnConversion(allocator, writer, program, child, "result", false);
            try writer.writeAll(";\n");
            try writeSliceWrittenAssignments(writer, function);
            try writer.writeAll("    return 1;\n}\n");
            continue;
        }

        if (function.origin.@"return" == .error_union) {
            const error_union = function.origin.@"return".error_union;
            if (function.value_union_return) {
                const declaration = type_spelling.enumDecl(program, error_union.payload.*.value_struct.ref);
                try writer.writeAll("const result = ");
                try writeTargetCall(allocator, writer, program, function);
                try writer.print(";\n    out_result.* = std.mem.zeroes({s});\n    switch (result) {{\n", .{function.payload_struct.?.c_name});
                for (declaration.fields) |field| {
                    if (declaration.variantOmitted(field.name)) {
                        try writer.print("        .{s} => return -3,\n", .{field.name});
                        continue;
                    }
                    try writer.print("        .{s} => ", .{field.name});
                    if (field.type.? == .void) {
                        try writer.print("out_result.tag = {d},\n", .{field.value.?});
                        continue;
                    }
                    try writer.print("|value| {{\n            out_result.tag = {d};", .{field.value.?});
                    try writeValueUnionReturnAssignments(allocator, writer, program, field.type.?, field.atomic orelse false, field.name, "value");
                    try writer.writeAll("\n        },\n");
                }
                try writer.writeAll("    }\n    return 0;\n}\n");
                continue;
            }
            if (error_union.payload.* == .void) {
                try writeTargetCall(allocator, writer, program, function);
                try writeShimErrorCatch(writer, function);
            } else {
                try writer.writeAll("const result = ");
                try writeTargetCall(allocator, writer, program, function);
                try writeShimErrorCatch(writer, function);
                // The out parameters stay untouched on the error path: the
                // early `return` above leaves before either assignment, so a
                // caller that checks the code first never reads them.
                if (error_union.payload.* == .slice) {
                    try writeShimSliceReturn(writer, program, function, "result");
                } else if (semantic.isOptionalSlice(error_union.payload.*) and
                    !(function.ret_string == .c_string))
                {
                    try writer.writeAll("    if (result) |zigo_value| {\n        out_result_ptr.* = zigo_value.ptr;\n" ++
                        "        out_result_len.* = zigo_value.len;\n    } else {\n        out_result_ptr.* = null;\n" ++
                        "        out_result_len.* = 0;\n    }\n");
                } else if (error_union.payload.* == .optional) {
                    // The status code is spent on the error, so presence needs
                    // its own out parameter; the value one stays untouched
                    // when the payload is absent.
                    try writer.writeAll("    if (result) |zigo_value| {\n        out_result_has.* = 1;\n        out_result.* = ");
                    const child = error_union.payload.optional.child.*;
                    try writeZigReturnConversion(allocator, writer, program, child, "zigo_value", false);
                    try writer.writeAll(";\n    } else {\n        out_result_has.* = 0;\n    }\n");
                } else {
                    try writer.writeAll("    out_result.* = ");
                    try writeZigReturnConversion(allocator, writer, program, error_union.payload.*, "result", function.origin.return_atomic orelse false);
                    try writer.writeAll(";\n");
                }
            }
            try writeSliceWrittenAssignments(writer, function);
            // The storage was allocated by the shim, so the shim is what frees
            // it, after the Zig destructor has had the object.
            if (function.origin.boxed == .destroy)
                try writer.print("    {s}.destroy(self);\n", .{program.allocator.?});
            try writer.writeAll("    return 0;\n}\n");
            continue;
        }

        // A plain result has to be named before the written counts can quote
        // it, so a function with output slices binds it and returns the binding
        // rather than returning the call directly.
        // A packed struct crosses as its backing integer, so only an aggregate
        // struct return is written through the out pointer.
        const packed_return = type_spelling.isPackedValue(program, function.origin.@"return");
        const struct_return = function.origin.@"return" == .value_struct and !packed_return;
        const binds_result = function.origin.@"return" != .void and !struct_return and hasOutSliceParam(function);
        const atomic_struct_return = struct_return and
            raw.recordHasAtomicFields(program, raw.structRecord(program, function.origin.@"return".value_struct.ref));
        if (atomic_struct_return) {
            try writer.writeAll("const result = ");
        } else if (struct_return) {
            try writer.writeAll("out_result.* = ");
        } else if (binds_result) {
            try writer.writeAll("const result = ");
        } else if (function.origin.@"return" != .void) {
            try writer.writeAll("return ");
        }
        // Narrowing never happens here: the result travels in a wider C
        // integer, so the cast is always in range.
        const narrow_return = abi.narrowInt(function.origin.@"return") != null;
        if (packed_return) try type_spelling.writePackedZigToBackingPrefix(writer, program, function.origin.@"return");
        if (narrow_return) try writer.writeAll("@intCast(");
        try writeTargetCall(allocator, writer, program, function);
        if (narrow_return) try writer.writeByte(')');
        if (packed_return) try writer.writeAll(")))");
        try writer.writeAll(";\n");
        if (atomic_struct_return) {
            try writer.writeAll("    out_result.* = ");
            try raw.writeZigAtomicStructCopy(
                allocator,
                writer,
                program,
                raw.structRecord(program, function.origin.@"return".value_struct.ref),
                "result",
            );
            try writer.writeAll(";\n");
        }
        try writeSliceWrittenAssignments(writer, function);
        if (binds_result) try writer.writeAll("    return result;\n");
        try writer.writeAll("}\n");
    }
    try renderTaggedUnionShim(writer, program);
    try renderTaggedUnionSnapshotShim(writer, program);
    try renderValueStructShim(writer, program);
}

fn writeValueUnionReturnAssignments(
    allocator: std.mem.Allocator,
    writer: *std.Io.Writer,
    program: abi.Program,
    node: semantic.TypeNode,
    atomic: bool,
    field_name: []const u8,
    expression: []const u8,
) !void {
    if (node == .value_struct) {
        const declaration = type_spelling.enumDecl(program, node.value_struct.ref);
        if (declaration.layout == .@"packed") {
            const backing = declaration.backing_type.?.int;
            try writer.print("\n            out_result.{s} = @intCast(@as({c}{d}, @bitCast({s})));", .{
                field_name,
                if (backing.signed) @as(u8, 'i') else @as(u8, 'u'),
                backing.bits,
                expression,
            });
            return;
        }
        for (declaration.fields) |field| {
            const child_name = try std.fmt.allocPrint(allocator, "{s}_{s}", .{ field_name, field.name });
            defer allocator.free(child_name);
            const child_expression = try std.fmt.allocPrint(allocator, "{s}.{s}", .{ expression, field.name });
            defer allocator.free(child_expression);
            try writeValueUnionReturnAssignments(allocator, writer, program, field.type.?, field.atomic orelse false, child_name, child_expression);
        }
        return;
    }
    try writer.print("\n            out_result.{s} = ", .{field_name});
    try writeZigReturnConversion(allocator, writer, program, node, expression, atomic);
    try writer.writeByte(';');
}

fn writeFieldAccess(
    allocator: std.mem.Allocator,
    writer: *std.Io.Writer,
    program: abi.Program,
    function: abi.AbiFn,
    access: semantic.FieldAccess,
) !void {
    const checked = function.origin.@"return" == .error_union;
    const trailer = if (checked) ";\n    return 0;\n}\n" else ";\n}\n";
    if (access.setter) {
        if (access.atomic orelse false) {
            try writer.print("self.{s}.store(", .{access.path});
            try writeShimInboundValue(writer, program, "v", function.origin.params[0].type, false);
            try writer.writeAll(", .seq_cst)");
        } else {
            try writer.print("self.{s} = ", .{access.path});
            try writeShimInboundValue(writer, program, "v", function.origin.params[0].type, false);
        }
        try writer.writeAll(trailer);
        return;
    }

    const field_type = if (checked)
        function.origin.@"return".error_union.payload.*
    else
        function.origin.@"return";
    if (checked)
        try writer.writeAll("out_result.* = ")
    else
        try writer.writeAll("return ");
    const expression = if (access.atomic orelse false)
        try std.fmt.allocPrint(allocator, "self.{s}.load(.seq_cst)", .{access.path})
    else
        try std.fmt.allocPrint(allocator, "self.{s}", .{access.path});
    defer allocator.free(expression);
    try writeZigReturnConversion(allocator, writer, program, field_type, expression, false);
    try writer.writeAll(trailer);
}

/// `extern` already fixes the layout on both sides, so the shim asserts rather
/// than converts: if the Zig struct ever stops matching the C mirror the
/// generated code fails to build instead of misreading memory.
///
/// Reflection runs on the build host, so these are also what makes
/// cross-compilation safe: a host layout that does not describe the target
/// fails this compile with a named diagnostic instead of shipping a struct
/// whose C and Go mirrors disagree with the Zig one.
fn renderValueStructShim(writer: *std.Io.Writer, program: abi.Program) !void {
    if (program.structs.len == 0) return;
    for (program.structs) |record| {
        if (record.owner.kind != .tagged_union) continue;
        try writer.print("\nconst {s} = extern struct {{\n", .{record.c_name});
        for (record.fields) |field| {
            try writer.print("    {s}: ", .{field.name});
            try type_spelling.writeZigType(writer, program, field.scalar);
            try writer.writeAll(",\n");
        }
        try writer.writeAll("};\n");
    }
    try writer.writeAll(abi_guard_helper);
    for (program.structs) |record| {
        if (record.owner.kind == .tagged_union) continue;
        try writer.print(
            "\ncomptime {{\n    zigoAbiGuard(\"@sizeOf({0s})\", {1d}, @sizeOf(target.{0s}));\n" ++
                "    zigoAbiGuard(\"@alignOf({0s})\", {2d}, @alignOf(target.{0s}));\n",
            .{ record.name, record.size, record.alignment },
        );
        for (record.fields) |field| {
            try writer.print(
                "    zigoAbiGuard(\"@offsetOf({0s}, \\\"{1s}\\\")\", {2d}, @offsetOf(target.{0s}, \"{1s}\"));\n",
                .{ record.name, field.name, field.offset },
            );
        }
        try writer.writeAll("}\n");
    }
}

/// The guard body, emitted once whenever the shim mirrors at least one user
/// struct. `@compileError` rather than `std.debug.assert` so the failure names
/// the struct, the member, both values, and the cause a user can act on --
/// `assert` reports only "reached unreachable code".
/// The `std.Io` adapters the shim wraps around a Go `io.Writer` or
/// `io.Reader`, taken verbatim from `stream_adapter.zig`. They live in a real
/// Zig file rather than in a string here so the drain and stream contracts are
/// compiled and tested where they are written; this embeds the region between
/// its markers, so the generated shim and the tested code cannot drift apart.
///
/// One copy per shim file, not per function: the signature is fixed by the
/// direction, so every stream parameter in the binding shares it.
const stream_adapters = blk: {
    // Scanning a few kilobytes for the markers is well past Zig's default
    // comptime branch quota.
    @setEvalBranchQuota(100_000);
    const source = @embedFile("stream_adapter.zig");
    const opening = "// zigo:adapters-begin\n";
    const closing = "// zigo:adapters-end\n";
    const first = std.mem.indexOf(u8, source, opening).? + opening.len;
    const last = std.mem.indexOf(u8, source, closing).?;
    break :blk source[first..last];
};

