//! Make-time halves of the build integration: the paths and native link
//! inputs `build.zig` can only name as lazy paths, resolved here once the
//! build runner has turned them into real directories.
const std = @import("std");

/// `to` relative to `from`, with forward slashes. The result is baked into
/// generated Go, which expects forward slashes on every host, and the
/// committed bytes must not depend on where generation ran.
pub fn relativeSlashPath(allocator: std.mem.Allocator, from: []const u8, to: []const u8) ![]u8 {
    const relative = try std.fs.path.relativeAlloc(allocator, "", null, from, to);
    std.mem.replaceScalar(u8, relative, std.fs.path.sep_windows, std.fs.path.sep_posix);
    return relative;
}

/// `to` spelled for a cgo directive in a file that lives in `from`.
pub fn cgoRelativePath(allocator: std.mem.Allocator, from: []const u8, to: []const u8) ![]u8 {
    const relative = try relativeSlashPath(allocator, from, to);
    defer allocator.free(relative);
    return std.fmt.allocPrint(allocator, "${{SRCDIR}}/{s}", .{relative});
}

/// `-L<dir>` for every directory, then `rest`, joined by spaces.
pub fn systemLdflags(allocator: std.mem.Allocator, library_dirs: []const []const u8, rest: []const u8) ![]u8 {
    var output: std.Io.Writer.Allocating = .init(allocator);
    defer output.deinit();
    for (library_dirs, 0..) |dir, index| {
        if (index != 0) try output.writer.writeByte(' ');
        try output.writer.print("-L{s}", .{dir});
    }
    if (rest.len != 0) {
        if (library_dirs.len != 0) try output.writer.writeByte(' ');
        try output.writer.writeAll(rest);
    }
    return output.toOwnedSlice();
}

/// The link line of one native target in the volatile cgo link file.
pub const LinkTarget = struct {
    /// Build constraint spelled before `LDFLAGS`, such as `darwin,arm64`.
    /// Empty writes the unqualified line a single-target tree links with.
    constraint: []const u8 = "",
    /// Where this target's archives install.
    library_dir: []const u8,
    /// `lib<name>.a` file names, the binding archive first.
    archives: []const []const u8,
};

pub const LinkFlags = struct {
    package: []const u8,
    /// The directory the link file lives in.
    source_dir: []const u8,
    targets: []const LinkTarget,
    extra_ldflags: []const u8 = "",
    system_ldflags: []const u8 = "",
};

/// The cgo directive that names static archive inputs. It lives outside the
/// checked generator tree: the archives exist only after a build, and the
/// directive is only present when a module has such inputs, so a checkout
/// that has not built yet has nothing stale to compare against.
pub fn writeLinkFlags(allocator: std.mem.Allocator, writer: *std.Io.Writer, options: LinkFlags) !void {
    try writer.print(
        "// Code generated by zigo. DO NOT EDIT.\n" ++
            "// This machine-local file is intentionally excluded from go-check.\n\n" ++
            "package {s}\n\n/*",
        .{options.package},
    );
    for (options.targets) |target| {
        const library_dir = try cgoRelativePath(allocator, options.source_dir, target.library_dir);
        defer allocator.free(library_dir);
        try writer.writeAll("\n#cgo ");
        if (target.constraint.len != 0) try writer.print("{s} ", .{target.constraint});
        try writer.writeAll("LDFLAGS:");
        for (target.archives) |archive| try writer.print(" {s}/{s}", .{ library_dir, archive });
        if (options.extra_ldflags.len != 0) try writer.print(" {s}", .{options.extra_ldflags});
        if (options.system_ldflags.len != 0) try writer.print(" {s}", .{options.system_ldflags});
    }
    try writer.writeAll("\n*/\nimport \"C\"\n");
}

/// One library a module links with `use_pkg_config = .force`.
pub const PkgConfigInput = struct {
    name: []const u8,
    /// The module that declared it, for the diagnostic.
    module: []const u8,
};

pub const PkgConfigError = error{PkgConfigUnresolved};

/// The pkg-config name of every input, space separated: the declared name,
/// or `lib<name>` when only that resolves. A missing pkg-config keeps the
/// declared name with a warning; an unresolvable name is an error naming the
/// module that declared it.
pub fn resolvePkgConfig(
    allocator: std.mem.Allocator,
    io: std.Io,
    executable: []const u8,
    inputs: []const PkgConfigInput,
    stdout: *std.Io.Writer,
    stderr: *std.Io.Writer,
) !void {
    for (inputs, 0..) |input, index| {
        const prefixed = try std.fmt.allocPrint(allocator, "lib{s}", .{input.name});
        defer allocator.free(prefixed);
        const resolved = blk: {
            for ([_][]const u8{ input.name, prefixed }) |candidate| switch (try probe(allocator, io, executable, candidate)) {
                .found => break :blk candidate,
                .missing_executable => {
                    try stderr.print("warning: pkg-config is unavailable; keeping original package name '{s}' declared by module '{s}'\n", .{ input.name, input.module });
                    break :blk input.name;
                },
                .not_found => {},
            };
            try stderr.print(
                "error: pkg-config could not resolve library '{s}' declared by module '{s}' (tried '{s}' and '{s}')\n",
                .{ input.name, input.module, input.name, prefixed },
            );
            return error.PkgConfigUnresolved;
        };
        if (index != 0) try stdout.writeByte(' ');
        try stdout.writeAll(resolved);
    }
}

const Probe = enum { found, not_found, missing_executable };

fn probe(allocator: std.mem.Allocator, io: std.Io, executable: []const u8, package: []const u8) !Probe {
    const result = std.process.run(allocator, io, .{
        .argv = &.{ executable, "--exists", package },
        .stdout_limit = .limited(64 * 1024),
        .stderr_limit = .limited(64 * 1024),
    }) catch |err| switch (err) {
        error.FileNotFound, error.InvalidName => return .missing_executable,
        else => return err,
    };
    defer allocator.free(result.stdout);
    defer allocator.free(result.stderr);
    return switch (result.term) {
        .exited => |code| if (code == 0) .found else .not_found,
        else => error.PkgConfigTerminated,
    };
}

test "cgo relative paths use forward slashes under SRCDIR" {
    const allocator = std.testing.allocator;
    const path = try cgoRelativePath(allocator, "/work/go/internal/raw", "/work/zig-out/lib");
    defer allocator.free(path);
    try std.testing.expectEqualStrings("${SRCDIR}/../../../zig-out/lib", path);
}

test "system ldflags put search directories before libraries" {
    const allocator = std.testing.allocator;
    const flags = try systemLdflags(allocator, &.{ "/a", "/b" }, "-lz");
    defer allocator.free(flags);
    try std.testing.expectEqualStrings("-L/a -L/b -lz", flags);
    const only = try systemLdflags(allocator, &.{}, "-lz");
    defer allocator.free(only);
    try std.testing.expectEqualStrings("-lz", only);
}

test "link flags name every archive relative to the source directory" {
    const allocator = std.testing.allocator;
    var output: std.Io.Writer.Allocating = .init(allocator);
    defer output.deinit();
    try writeLinkFlags(allocator, &output.writer, .{
        .package = "raw",
        .source_dir = "/w/go/internal/raw",
        .targets = &.{.{ .library_dir = "/w/zig-out/lib", .archives = &.{ "libdemo_zigo.a", "libdep.a" } }},
        .system_ldflags = "-lm",
    });
    try std.testing.expectEqualStrings(
        "// Code generated by zigo. DO NOT EDIT.\n" ++
            "// This machine-local file is intentionally excluded from go-check.\n\n" ++
            "package raw\n\n/*\n#cgo LDFLAGS: ${SRCDIR}/../../../zig-out/lib/libdemo_zigo.a ${SRCDIR}/../../../zig-out/lib/libdep.a -lm\n*/\nimport \"C\"\n",
        output.written(),
    );
}
